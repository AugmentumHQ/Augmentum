# competency.json — meta-info about this workspace's audit history
# ---------------------------------------------------------------------------


@dataclass
class Competency:
    """Aggregate state about how well the bug_finder has done on
    this workspace. Mutable; the orchestrator updates after each run."""

    audit_count: int = 0
    total_findings_ever: int = 0
    total_confirmed: int = 0
    total_fixed: int = 0
    total_false_positives: int = 0
    last_run_at: int = 0
    scanner_effectiveness: dict[str, float] = field(default_factory=dict)
    # ratio of (confirmed / produced) per scanner; higher = more
    # trustworthy. The lead weighs scanner output by this.

    def precision(self) -> float:
        if self.total_findings_ever == 0:
            return 0.0
        return self.total_confirmed / self.total_findings_ever


def _competency_path(root: Path) -> Path:
    return substrate_dir(root) / "competency.json"


def load_competency(root: Path) -> Competency:
    p = _competency_path(root)
    if not p.is_file():
        return Competency()
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return Competency()
    if not isinstance(data, dict):
        return Competency()
    se = data.get("scanner_effectiveness") or {}
    return Competency(
        audit_count=int(data.get("audit_count") or 0),
        total_findings_ever=int(data.get("total_findings_ever") or 0),
        total_confirmed=int(data.get("total_confirmed") or 0),
        total_fixed=int(data.get("total_fixed") or 0),
        total_false_positives=int(data.get("total_false_positives") or 0),
        last_run_at=int(data.get("last_run_at") or 0),
        scanner_effectiveness={
            str(k): float(v) for k, v in se.items()
        } if isinstance(se, dict) else {},
    )


def save_competency(root: Path, c: Competency) -> None:
    ensure_substrate(root)
    _atomic_write_json(_competency_path(root), {
        "audit_count": c.audit_count,
        "total_findings_ever": c.total_findings_ever,
        "total_confirmed": c.total_confirmed,
        "total_fixed": c.total_fixed,
        "total_false_positives": c.total_false_positives,
        "last_run_at": c.last_run_at,
        "scanner_effectiveness": c.scanner_effectiveness,
    })


# ---------------------------------------------------------------------------
# audit_history.jsonl — append-only trend log
# ---------------------------------------------------------------------------


def _history_path(root: Path) -> Path:
    return substrate_dir(root) / "audit_history.jsonl"


def append_audit_history(
    root: Path,
    *,
    run_id: str,
    duration_seconds: float,
    findings_by_severity: dict[str, int],
    confirmed: int = 0,
    fixed: int = 0,
    mode: str = "explore",
    tokens_used: int = 0,
    notes: list[str] | None = None,
) -> None:
    """Append one row to the trend log."""
    ensure_substrate(root)
    row = {
        "ts": int(time.time()),
        "run_id": run_id,
        "duration_seconds": round(duration_seconds, 2),
        "findings_by_severity": dict(findings_by_severity),
        "confirmed": confirmed,
        "fixed": fixed,
        "mode": mode,
        "tokens_used": tokens_used,
        "notes": notes or [],
    }
    try:
        with _history_path(root).open("a", encoding="utf-8") as fp:
            fp.write(json.dumps(row, ensure_ascii=False) + "\n")
    except OSError as exc:
        log.warning(
            "bug_finder_audit_history_append_failed",
            workspace=str(root), error=str(exc),
        )


def load_audit_history(
    root: Path, *, limit: int = 50,
) -> list[dict[str, Any]]:
    p = _history_path(root)
    if not p.is_file():
        return []
    try:
        lines = p.read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    out: list[dict[str, Any]] = []
    for line in lines[-limit:]:
        line = line.strip()
        if not line:
            continue
        try:
            d = json.loads(line)
            if isinstance(d, dict):
                out.append(d)
        except ValueError:
            continue
    return out


# ---------------------------------------------------------------------------
# Atomic write helper
# ---------------------------------------------------------------------------


_WRITE_LOCK = threading.Lock()


def _atomic_write_json(path: Path, payload: Any) -> None:
    """Write JSON to ``path`` atomically.

    Uses a sibling ``.tmp`` file + rename so partial writes never
    corrupt the live state. Thread-safe via a process-local lock —
    multiple bug_finder runs concurrently writing to the same
    workspace substrate would otherwise race.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with _WRITE_LOCK:
        with tmp.open("w", encoding="utf-8") as fp:
            json.dump(payload, fp, indent=2, ensure_ascii=False)
        tmp.replace(path)


# ---------------------------------------------------------------------------
# Prior-knowledge brief for the planner / lead
# ---------------------------------------------------------------------------


def unresolved_workspace_patterns(
    patterns: list[WorkspacePattern],
    *,
    min_hit_count: int = 1,
    limit: int = 20,
) -> list[WorkspacePattern]:
    """Patterns the fixer has never closed in this workspace.

    The planner consumes these as priors — "these signatures appeared
    before and were never resolved, so the code that triggered them
    is probably still buggy." Sorted by recency so the most recently
    observed unresolved patterns surface first.
    """
    candidates = [
        p for p in patterns
        if p.is_unresolved and p.hit_count >= min_hit_count
    ]
    candidates.sort(key=lambda p: p.last_seen_at, reverse=True)
    return candidates[:limit]


def familiar_workspace_patterns(
    patterns: list[WorkspacePattern],
    *,
    min_hit_count: int = 3,
    limit: int = 10,
) -> list[WorkspacePattern]:
    """Patterns this workspace has seen many times across runs.

    High recurrence count is a precision signal: when a signature has
    been flagged 3+ times and the fixer agreed at least once, the next
    surfacing is more likely to be real. Used as a planner prior to
    weight where to focus attention.
    """
    candidates = [p for p in patterns if p.hit_count >= min_hit_count]
    candidates.sort(key=lambda p: p.hit_count, reverse=True)
    return candidates[:limit]


def render_pattern_priors(
    patterns: list[WorkspacePattern],
    *,
    max_unresolved: int = 8,
    max_familiar: int = 5,
) -> str:
    """Compact "what this workspace has seen before" brief.

    Empty string when no prior knowledge exists — first-contact runs
    on a fresh workspace flow through unchanged, no prompt change.

    Layout: two short lists. **Unresolved** (likely still-present
    bugs) first because they're more actionable; **familiar** (high
    recurrence) second as a hotspot signal for where to focus.

    Surfaced to the planner + lead, NEVER the detector — the detector
    must reason from evidence in front of it, not from priors that
    could bias it toward confirming earlier findings.
    """
    if not patterns:
        return ""
    unresolved = unresolved_workspace_patterns(
        patterns, limit=max_unresolved,
    )
    familiar = familiar_workspace_patterns(patterns, limit=max_familiar)
    # Filter familiar to not overlap with unresolved — no value showing
    # the same row twice.
    unresolved_keys = {(p.signature, p.file_pattern) for p in unresolved}
    familiar = [
        p for p in familiar
        if (p.signature, p.file_pattern) not in unresolved_keys
    ]
    if not unresolved and not familiar:
        return ""
    lines: list[str] = []
    lines.append("## Prior bug patterns observed in this workspace")
    lines.append("")
    lines.append(
        "Use as a WHERE-to-look prior, not a WHAT-to-flag prior. "
        "Every finding still needs its own evidence — these are "
        "hotspot signals from past audits, not confirmed claims.",
    )
    if unresolved:
        lines.append("")
        lines.append(
            "**Unresolved** (flagged before, no successful fix recorded):",
        )
        for p in unresolved:
            sample = (p.sample_claim or "").strip()
            sample_tail = f" — {sample[:80]}" if sample else ""
            lines.append(
                f"  - `{p.signature}` in `{p.file_pattern}` "
                f"(×{p.hit_count} hits; severity {p.severity})"
                f"{sample_tail}",
            )
    if familiar:
        lines.append("")
        lines.append(
            "**Familiar** (high-recurrence, partially resolved):",
        )
        for p in familiar:
            lines.append(
                f"  - `{p.signature}` in `{p.file_pattern}` "
                f"(×{p.hit_count} hits, {p.fix_count} fixed)",
            )
    return "\n".join(lines)
