@router.post("/send/system-volume")
async def cast_send_system_volume(
    request: Request, body: SystemVolumeRequest,
) -> dict[str, Any]:
    """Send a device-level (NOT surface-scoped) system-volume command.

    Only effective when the receiver is the bundled Android TV APK —
    that's the only context where the AugmentumTV JS bridge exists.
    Browser receivers acknowledge the cmd but the bridge feature-
    detect returns ``supported: false`` and they no-op. Either way
    the receiver emits ``system_volume_state`` so the controller can
    update its slider position to match reality.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")

    registry = getattr(request.app.state, "receiver_registry", None)
    if registry is None:
        raise HTTPException(503, "receiver registry not initialised")

    receiver = registry.get(body.receiver_id)
    if receiver is None or receiver.user_id != user.id:
        raise HTTPException(404, "receiver not connected or not owned by you")

    args: dict[str, Any] = {}
    if body.volume is not None:
        args["volume"] = max(0.0, min(1.0, float(body.volume)))
    if body.delta is not None:
        args["delta"] = int(body.delta)
    if body.muted is not None:
        args["muted"] = bool(body.muted)
    if not args:
        raise HTTPException(422, "specify at least one of volume / delta / muted")

    from augmentum.cast.receiver_protocol import CMD_SYSTEM_VOLUME, ReceiverCmd
    cmd = ReceiverCmd(cmd=CMD_SYSTEM_VOLUME, args=args)
    ok = await registry.send(body.receiver_id, cmd)
    if not ok:
        raise HTTPException(502, "receiver send failed")
    return {"ok": True, "receiver_id": body.receiver_id, "applied": args}


