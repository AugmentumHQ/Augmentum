@router.post("/send")
async def cast_send(request: Request, body: SurfaceSendRequest) -> dict[str, Any]:
    """Orchestrator-facing dispatch endpoint.

    Any caller that wants to put a surface on a receiver hits this:
    UI cast buttons, companion routines, automated test fixtures.
    Auth-required because dispatching to a receiver affects what's
    on the user's TV.

    On success, records a cast event so the user can see "currently
    showing" + recent activity. Updates the trusted receiver's
    ``last_cast_at`` for sort-by-recency in the UI.

    Returns 404 when the receiver is gone (so the caller can react),
    422 on a bad slot, 200 with surface_id on success.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    if not is_valid_slot(body.slot):
        raise HTTPException(
            422,
            f"unknown slot {body.slot!r}; valid: {', '.join(SLOTS)}",
        )

    registry = getattr(request.app.state, "receiver_registry", None)
    if registry is None:
        raise HTTPException(503, "receiver registry not initialised")

    receiver = registry.get(body.receiver_id)
    if receiver is None or receiver.user_id != user.id:
        raise HTTPException(404, "receiver not connected or not owned by you")

    sid = await _cast_surface(
        registry, body.receiver_id,
        surface_kind=body.surface_kind,
        surface_url=body.surface_url,
        slot=body.slot,
        state=body.state,
        surface_id=body.surface_id or None,
    )
    if sid is None:
        raise HTTPException(502, "receiver send failed (connection dropped?)")

    # Audit + trusted bookkeeping — fire-and-forget so a slow DB
    # doesn't add latency to the cast dispatch. Failures here are
    # logged but don't fail the request.
    event_store = getattr(request.app.state, "cast_event_store", None)
    trusted_store = getattr(request.app.state, "trusted_receiver_store", None)
    if event_store is not None:
        try:
            await event_store.record_start(
                user_id=user.id,
                trusted_id=receiver.trusted_id,
                registration_id=body.receiver_id,
                surface_id=sid,
                surface_kind=body.surface_kind,
                surface_url=body.surface_url,
                slot=body.slot,
            )
        except Exception as exc:
            log.warning("cast_event_record_start_failed", error=str(exc))
    if trusted_store is not None and receiver.trusted_id:
        try:
            await trusted_store.mark_cast(receiver.trusted_id, user_id=user.id)
        except Exception as exc:
            log.warning("trusted_receiver_mark_cast_failed", error=str(exc))

    return {"surface_id": sid, "receiver_id": body.receiver_id, "slot": body.slot}


def _entry_to_tile(entry: Any) -> dict[str, Any] | None:
    """Convert a FileEntry into a tile dict the cast surfaces consume.

    Both /ui/cast-home/ (TV idle) and /ui/cast-control/ (phone remote)
    render the same tile shape, so the aggregator returns it once and
    both surfaces map directly. The ``play`` block tells the cast-
    control client exactly which surface_kind + URL to send when the
    user taps — keeping all the kind/URL routing on the server.

    Returns ``None`` for entries we genuinely can't render — bare docs,
    seasons that aren't a useful card on their own, video entries
    without a streamable source. Series cards are included with a
    ``play.action == "browse_series"`` so the controller can route
    them through the episode-drill-in instead of trying to cast.
    """
    meta = entry.source_metadata if isinstance(entry.source_metadata, dict) else {}
    kind = (entry.kind or "").lower()
    entity_kind = str(meta.get("entity_kind") or "").strip().lower()
    server_id = str(meta.get("server_id") or "").strip()
    source = entry.source or ""

    # Build the play descriptor. Each branch picks the right surface +
    # URL for the entry's actual provenance. Series get a special
    # ``browse_series`` action since they aren't directly playable.
    surface_kind = ""
    surface_url = ""
    action = "cast"  # default — controller dispatches via /api/cast/send

    if kind == "audio":
        surface_kind = "html.generic"
        surface_url = f"/ui/cast-audio/?id={entry.id}"

    elif kind == "video":
        if entity_kind == "season":
            # Seasons carry the upstream's raw scene-release name and
            # no useful card art — surface the SERIES tile instead.
            return None
        if entity_kind == "series":
            # Special-cased: not directly castable, route the tap
            # through a browse drill-in. Episodes inside will be
            # listed via /api/cast/library/episodes/{file_id}.
            action = "browse_series"
        elif not server_id:
            return None
        else:
            surface_kind = "html.generic"
            surface_url = f"/ui/cast-video/?id={entry.id}"

    elif kind == "comic":
        surface_kind = "html.generic"
        surface_url = f"/ui/cast-comic/?id={entry.id}"

    elif kind == "image":
        # Same per-source split as covers: server-backed image
        # libraries flow through /api/media/cover (provider auth +
        # dispatch); local image_generations / chat_images / artifacts
        # / uploads flow through /api/files/thumb at the large tier.
        surface_kind = "media.image"
        if server_id:
            surface_url = f"/api/media/cover/{entry.id}"
        else:
            surface_url = f"/api/files/thumb/{entry.id}?size=800"

    else:
        return None

    # ── Cover URL — per-source routing ─────────────────────────
    # Media-server-backed entries (Emby / Jellyfin / Audiobookshelf /
    # Suwayomi / Komga) carry a ``server_id`` and their thumbnails
    # live upstream — only ``/api/media/cover/{id}`` can fetch them
    # because it dispatches per-provider with the right auth. Local
    # entries (image_generations / chat_images / artifacts / uploads)
    # have file_index thumbnails — ``/api/files/thumb/{id}`` handles
    # those. Picking the wrong endpoint for the wrong source 404s
    # silently and the tile shows a placeholder.
    if server_id:
        cover_url = f"/api/media/cover/{entry.id}"
    else:
        cover_url = f"/api/files/thumb/{entry.id}?size=300"

    # Title polish: series-level entries already have clean names, so
    # use entry.name. For episodes, prefix with series + S/E so the
    # row reads cleanly in the "Continue" rail.
    title = entry.name or "Untitled"
    subtitle_bits: list[str] = []
    if entity_kind == "episode":
        sname = str(meta.get("series_name") or "").strip()
        season_n = meta.get("season_number") or 0
        episode_n = meta.get("episode_number") or 0
        if sname:
            subtitle_bits.append(sname)
        if season_n and episode_n:
            subtitle_bits.append(f"S{int(season_n)}E{int(episode_n):02d}")
    elif entity_kind == "series":
        # Series cards get an episode-count hint when available.
        unplayed = int(meta.get("unplayed_count") or 0)
        if unplayed:
            subtitle_bits.append(f"{unplayed} unwatched")
        elif meta.get("year"):
            subtitle_bits.append(str(meta["year"]))
    else:
        sub = str(meta.get("author") or meta.get("series") or "")
        if sub:
            subtitle_bits.append(sub)
        if meta.get("year"):
            subtitle_bits.append(str(meta["year"]))

    return {
        "file_id": entry.id,
        "title": title,
        "subtitle": " · ".join(subtitle_bits),
        "kind": kind,
        "entity_kind": entity_kind,
        "source": source,
        "cover_url": cover_url,
        "backdrop_url": f"/api/media/backdrop/{entry.id}" if kind == "video" else "",
        "progress_pct": float(meta.get("progress_pct") or 0.0),
        "duration_s": float(meta.get("duration_s") or 0.0),
        # Presentation depth for the Media surface (and, later, the cast
        # surfaces): watched checkmark, series unplayed-count badge, and
        # year are all already in source_metadata — surfacing them here
        # costs nothing and saves a per-tile details fetch.
        "year": int(meta.get("year") or 0),
        "is_finished": bool(meta.get("is_finished")),
        "unplayed_count": int(meta.get("unplayed_count") or 0),
        "play": {
            "action": action,
            "surface_kind": surface_kind,
            "surface_url": surface_url,
        },
    }


# Comic library fetch sizing. The series-collapse + drill-in paths
# all need to see every chapter the user has — silently truncating
# means series with old chapters vanish from the rail and chapter
# lists arrive empty (this is the failure mode the prior fixed cap
# would hit once a library exceeded the cap by even one chapter).
#
# Instead of a single fixed cap, we count the user's library on each
# fetch and size accordingly, with a high ceiling for safety against
# pathological libraries that would OOM the container. The ceiling is
# user-configurable via the ``cast_comic_library_ceiling`` setting so
# users running 500k+ chapter libraries can crank it without code
# edits. Default ceiling at 200k covers any realistic personal
# library with ~10× headroom over our reference heavy user (20k).
COMIC_LIBRARY_DEFAULT_CEILING = 200_000
COMIC_LIBRARY_MIN_FETCH = 1000      # smallest fetch even for tiny libraries
COMIC_LIBRARY_FETCH_BUFFER = 200    # extra rows in case new chapters land
                                    # between the count and the fetch
COMIC_LIBRARY_CEILING_SETTING_KEY = "cast_comic_library_ceiling"


async def _resolved_comic_ceiling(request: Request) -> int:
    """Read the user-configurable comic library ceiling, with default."""
    settings_store = getattr(request.app.state, "settings_store", None)
    if settings_store is None:
        return COMIC_LIBRARY_DEFAULT_CEILING
    try:
        raw = await settings_store.get(COMIC_LIBRARY_CEILING_SETTING_KEY)
    except Exception:
        return COMIC_LIBRARY_DEFAULT_CEILING
    if not raw:
        return COMIC_LIBRARY_DEFAULT_CEILING
    try:
        val = int(raw)
    except (TypeError, ValueError):
        return COMIC_LIBRARY_DEFAULT_CEILING
    # Clamp to sane bounds — < MIN_FETCH would starve the rail, and
    # > 10M is clearly a typo (or someone trying to OOM us).
    return max(COMIC_LIBRARY_MIN_FETCH, min(val, 10_000_000))


async def _fetch_user_comic_chapters(
    request: Request,
    idx,
    user_id: str,
    *,
    extra_filters: dict[str, Any] | None = None,
) -> list:
    """Auto-sized comic-chapter fetch.

    Pre-flights a COUNT(*) on the user's comic library, asks
    list_recent for exactly that many rows (plus a small buffer in
    case new chapters arrive mid-flight), and clamps to the
    user-configurable ceiling. Warn-logs when the ceiling truncates
    so power users notice they should raise the setting instead of
    silently losing content from the rail.
    """
    ceiling = await _resolved_comic_ceiling(request)
    try:
        actual = await idx.count(user_id=user_id, kind="comic")
    except Exception as exc:
        log.warning("cast_comic_count_failed", user_id=user_id, error=str(exc))
        actual = ceiling  # safe pessimistic default if COUNT fails
    want = min(
        max(actual + COMIC_LIBRARY_FETCH_BUFFER, COMIC_LIBRARY_MIN_FETCH),
        ceiling,
    )
    if actual > ceiling:
        log.warning(
            "cast_comic_library_exceeds_ceiling",
            user_id=user_id, total_chapters=actual, ceiling=ceiling,
            dropped=actual - ceiling,
            setting_key=COMIC_LIBRARY_CEILING_SETTING_KEY,
        )
    filters = dict(extra_filters or {})
    filters.update({"user_id": user_id, "kind": "comic", "limit": want})
    return await idx.list_recent(**filters)


# ── Comic library collapsed-series cache ─────────────────────────
# /library/home and /library/section/comics both walk the full comic
# library (~20k rows for a heavy user), JSON-decode each row, and
# collapse to ~170 series tiles in Python. End-to-end that takes
# 6+ seconds and stalls the event loop. The collapsed result is
# stable on the order of "how often new chapters sync" (minutes,
# usually), so a short TTL is safe and kills the polling cost.
#
# Cache key = (user_id, chapter_count). Chapter count change
# invalidates immediately (a new chapter synced in), which is the
# only event that materially changes the rail. TTL bounds the cache
# in case count() somehow stays stable while metadata changes.
_COMIC_COLLAPSE_CACHE_TTL_S = 30.0
_comic_collapse_cache: dict[
    tuple[str, int], tuple[float, list[dict[str, Any]]]
] = {}


async def _get_collapsed_comic_series(
    request: Request, idx, user_id: str,
) -> list[dict[str, Any]]:
    """Return the user's full series-collapsed tile list, cached.

    Cache key includes the chapter count so any sync activity
    invalidates without waiting for the TTL. Falls back to a fresh
    collapse if the cache miss or the count check fails.
    """
    try:
        count = await idx.count(user_id=user_id, kind="comic")
    except Exception:
        count = -1  # uncacheable; do a fresh build
    cache_key = (user_id, count)
    entry = _comic_collapse_cache.get(cache_key)
    if entry is not None and count >= 0:
        ts, tiles = entry
        if time.monotonic() - ts < _COMIC_COLLAPSE_CACHE_TTL_S:
            return tiles
        _comic_collapse_cache.pop(cache_key, None)

    # Cache miss — rebuild. Drop stale entries for the same user
    # (different counts) so we don't accumulate one per chapter delta.
    for key in list(_comic_collapse_cache.keys()):
        if key[0] == user_id:
            _comic_collapse_cache.pop(key, None)

    entries = await _fetch_user_comic_chapters(request, idx, user_id)
    tiles = _collapse_comics_to_series(entries, len(entries) + 1)
    if count >= 0:
        _comic_collapse_cache[cache_key] = (time.monotonic(), tiles)
    return tiles


