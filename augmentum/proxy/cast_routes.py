@router.get("/trusted-receivers")
async def list_trusted_receivers(request: Request, include_revoked: bool = False) -> dict[str, Any]:
    """List durable receivers for the current user. Powers the
    Settings → TVs surface — names, last seen, last cast, revoke."""
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    store = getattr(request.app.state, "trusted_receiver_store", None)
    if store is None:
        return {"receivers": []}
    receivers = await store.list_for_user(
        user_id=user.id, include_revoked=include_revoked,
    )

    # Enrich each row with currently-showing surface(s) + live
    # connection state by joining with the in-memory registry. This
    # is the "what's on the TV right now" view.
    registry = getattr(request.app.state, "receiver_registry", None)
    event_store = getattr(request.app.state, "cast_event_store", None)
    out: list[dict[str, Any]] = []
    for r in receivers:
        item = r.to_dict()
        item["connected"] = False
        item["currently_showing"] = []
        live_conn = None
        if registry is not None:
            # Walk in-memory receivers; match by trusted_id.
            for conn in registry.list_for_user(user.id):
                if conn.trusted_id == r.id:
                    item["connected"] = True
                    item["registration_id"] = conn.registration_id
                    live_conn = conn
                    break
        if event_store is not None:
            active = await event_store.list_active_for_trusted(
                r.id, user_id=user.id,
            )
            showing = []
            for e in active:
                ev = e.to_dict()
                # Splice in the live surface state from the registry so
                # controller UIs (cast-shelf, cast-control) can render
                # scrubbers / pause buttons that match reality without
                # a second roundtrip. Stays absent when the receiver
                # is offline (no live_conn) or the surface hasn't
                # emitted state yet — clients handle missing state by
                # hiding the affected controls.
                if live_conn is not None:
                    state = live_conn.surface_states.get(e.surface_id)
                    if state:
                        ev["surface_state"] = dict(state)
                showing.append(ev)
            item["currently_showing"] = showing
        out.append(item)
    return {"receivers": out}


class TrustedReceiverPatchRequest(BaseModel):
    label: str | None = None
    # Wake-on-LAN settings. Empty string clears a field; None leaves
    # it alone. MAC and broadcast inputs are tolerant of common
    # write-styles (router-UI hyphens, no separators, mixed case) —
    # canonicalised before storage.
    mac_address: str | None = None
    wol_broadcast_override: str | None = None


@router.patch("/trusted-receivers/{trusted_id}")
async def update_trusted_receiver(
    trusted_id: str,
    request: Request,
    body: TrustedReceiverPatchRequest,
) -> dict[str, Any]:
    """Rename + edit WoL fields on a trusted receiver."""
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    store = getattr(request.app.state, "trusted_receiver_store", None)
    if store is None:
        raise HTTPException(503, "trusted-receiver store not initialised")
    if body.label is not None:
        label = body.label.strip()
        if not label:
            raise HTTPException(422, "label cannot be empty")
        if not await store.update_label(trusted_id, user_id=user.id, label=label):
            raise HTTPException(404, "trusted receiver not found")

    if body.mac_address is not None or body.wol_broadcast_override is not None:
        normalised_mac: str | None = None
        if body.mac_address is not None:
            stripped = body.mac_address.strip()
            if stripped:
                normalised_mac = normalise_mac(stripped)
                if not normalised_mac:
                    raise HTTPException(422, "invalid MAC address")
            else:
                normalised_mac = ""  # explicit clear

        normalised_bcast: str | None = None
        if body.wol_broadcast_override is not None:
            stripped = body.wol_broadcast_override.strip()
            if stripped:
                normalised_bcast = normalise_ipv4(stripped)
                if not normalised_bcast:
                    raise HTTPException(422, "invalid broadcast address")
            else:
                normalised_bcast = ""  # explicit clear

        applied = await store.set_wol_address(
            trusted_id,
            user_id=user.id,
            mac_address=normalised_mac,
            wol_broadcast_override=normalised_bcast,
        )
        if not applied:
            # Either the row doesn't exist for this user, or it's revoked.
            existing = await store.get(trusted_id, user_id=user.id)
            if existing is None:
                raise HTTPException(404, "trusted receiver not found")
            # Row exists — surface why the write was refused.
            raise HTTPException(409, "receiver is revoked; restore it first")

    updated = await store.get(trusted_id, user_id=user.id)
    if updated is None:
        raise HTTPException(404, "trusted receiver not found")
    return {"receiver": updated.to_dict()}


