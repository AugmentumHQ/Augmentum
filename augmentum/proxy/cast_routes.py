@stream_auth_router.get("/redeem")
async def cast_stream_auth_redeem(request: Request, t: str = "") -> Response:
    """Exchange a one-shot redeem token for an HTTP session cookie +
    redirect to the target URL.

    Auth: the ``t`` query param IS the credential. It's bound to a
    specific casting flow, single-use, ~30s TTL — generated by
    ``/api/cast/render-stream/start`` and embedded in the URL the
    rendering Chrome boots into. After redemption Chrome has the
    cookie and every subsequent ``/api/*`` from the surface page
    flies through middleware as the casting user.
    """
    store = getattr(request.app.state, "stream_auth_redeem_store", None)
    if store is None:
        raise HTTPException(503, "stream-auth redeem store not initialised")
    record = store.redeem(t)
    if record is None:
        raise HTTPException(401, "invalid or expired redeem token")

    is_https = (
        request.headers.get("x-forwarded-proto") == "https"
        or request.url.scheme == "https"
    )
    # Force absolute Location header — relative ones can be ambiguous
    # under reverse proxies. 303 (See Other) is correct semantics here
    # (GET resource at the new URL, irrespective of original method).
    response = RedirectResponse(url=record.next_url, status_code=303)
    response.set_cookie(
        "augmentum_session",
        record.session_token,
        httponly=True,
        secure=is_https,
        # Lax matches the cast-receiver establish-session cookie —
        # rendering Chrome may chase same-origin sub-resources that
        # the page bootstraps with full top-level semantics.
        samesite="lax",
        max_age=30 * 86400,
        path="/",
        domain=_cookie_domain(request),
    )
    return response


class RenderRequest(BaseModel):
    """Inbound render request body — used by both peer-side fabric
    calls and any direct local caller (single-machine tests, future
    UI surfaces dispatching against this node's executor).
    """
    kind: str
    target_device_id: str = ""
    payload: dict[str, Any] = Field(default_factory=dict)


def _filter_render(caps: list[CapabilityBase]) -> CastRenderCapability | None:
    """Pick the CastRenderCapability from a mixed capability list.

    Each node advertises exactly one cast-render cap, so we return the
    first match. None when the node hasn't yet run its extractors.
    """
    for cap in caps:
        if isinstance(cap, CastRenderCapability):
            return cap
    return None


async def _local_capability(request: Request) -> CastRenderCapability | None:
    """Return this node's cast-render cap.

    Prefer the coordinator's cached snapshot (refreshed on every
    heartbeat). On single-machine deployments where fabric is disabled,
    fall back to running the extractor inline so the diagnostic surface
    still has something to show — the extractor caches its detection so
    repeat calls are cheap.
    """
    coord = getattr(request.app.state, "fabric_coordinator", None)
    if coord is not None:
        cap = _filter_render(coord.local_capabilities())
        if cap is not None:
            return cap
        # Coordinator present but extractors haven't run yet — fall through
        # to inline detection rather than return an unhelpful empty state.

    try:
        from augmentum.fabric.extractors import CastRenderCapabilityExtractor
        caps = await CastRenderCapabilityExtractor().collect()
    except Exception:
        log.warning("cast_render_capability_inline_extract_failed", exc_info=True)
        return None
    return _filter_render(caps)


@router.get("/render-capabilities")
async def render_capabilities(request: Request) -> dict[str, Any]:
    """List this node's render capability + paired peers' render capabilities.

    Surface contract:

      {
        "local":  {"node_id": str, "capability": {...} | null},
        "peers":  [{"node_id": str, "label": str,
                    "connected": bool, "capability": {...} | null}, ...],
        "fabric_enabled": bool,
      }

    Single-machine deployments still get a useful "local" block; the
    "peers" array is just empty. This is intentional — the same data
    shape powers the diagnostic regardless of fabric state, so a UI
    rendering this doesn't need to special-case the no-peer path.
    """
    local_cap = await _local_capability(request)

    local_node_id = ""
    peers_out: list[dict[str, Any]] = []
    fabric_enabled = False

    coord = getattr(request.app.state, "fabric_coordinator", None)
    if coord is not None:
        fabric_enabled = True
        try:
            local_node_id = coord._identity.node_id  # noqa: SLF001 — read-only diagnostic
        except Exception:
            local_node_id = ""
        for node_id in coord.known_peer_ids():
            state = coord.peer_state(node_id)
            if state is None:
                continue
            cap = _filter_render(state.capabilities)
            paired = state.paired
            peers_out.append({
                "node_id": node_id,
                "label": getattr(paired, "label", "") or getattr(paired, "hostname", "") or node_id,
                "connected": bool(state.connected),
                "capability": asdict(cap) if cap is not None else None,
            })

    return {
        "local": {
            "node_id": local_node_id,
            "capability": asdict(local_cap) if local_cap is not None else None,
        },
        "peers": peers_out,
        "fabric_enabled": fabric_enabled,
        "kind": KIND_CAST_RENDER,
    }


@router.post("/render")
async def render_inbound(request: Request, body: RenderRequest) -> dict[str, Any]:
    """Inbound render endpoint.

    Hit by:
      - Peer nodes shipping work via :func:`render_via_peer` — fabric
        middleware authenticates them via signed envelope before this
        handler runs.
      - Direct local callers (tests, future surfaces) using normal
        session-cookie auth.

    Always runs the LOCAL executor on this node — receiving a render
    request never recurses into routing (that would loop). The
    dispatcher is the only thing that calls ``maybe_route_render``;
    this route just executes.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    user_id = getattr(user, "id", "")

    job = RenderJob(
        kind=body.kind,
        target_device_id=body.target_device_id,
        payload=body.payload,
    )

    local_node_id = ""
    coord = getattr(request.app.state, "fabric_coordinator", None)
    if coord is not None:
        try:
            local_node_id = coord._identity.node_id  # noqa: SLF001
        except Exception:
            local_node_id = ""

    html_renderer = getattr(request.app.state, "html_renderer", None)
    output_store = getattr(request.app.state, "render_output_store", None)

    result = await execute_local_render(
        job,
        node_id=local_node_id,
        user_id=user_id,
        html_renderer=html_renderer,
        output_store=output_store,
    )
    return asdict(result)


@router.websocket("/receiver/ws")
async def receiver_ws(websocket: WebSocket) -> None:
    """WebSocket endpoint for cast receivers (TV apps, browser tabs).

    Auth: relies on AuthMiddleware to have populated ``scope["user"]``
    via the user's session cookie. WS connections without auth are
    closed with policy-violation (1008). When TV-side launch flows
    land (Cast custom receiver, Android TV APK, etc.), a token-based
    handshake will be added — for foundation we use cookies.

    Lifecycle: accept → attach to registry → record inbound events →
    detach on close. Outbound cmds happen via the registry from other
    surfaces (dispatcher, future cast UI).
    """
    user = websocket.scope.get("user")
    if user is None:
        await websocket.close(code=1008, reason="auth required")
        return

    registry = getattr(websocket.app.state, "receiver_registry", None)
    if registry is None:
        await websocket.accept()
        await websocket.close(code=1011, reason="receiver registry not initialised")
        return

    await websocket.accept()
    receiver = registry.attach(ws=websocket, user_id=user.id)
    # Identity handshake — tell the receiver its own registration_id so
    # iframed surfaces (cast-home tile clicks) can POST /api/cast/send
    # with a valid receiver_id without needing a server lookup. Sent
    # before the receive loop so it's the first cmd the receiver sees.
    try:
        from augmentum.cast.receiver_protocol import CMD_IDENTITY, ReceiverCmd
        await registry.send(
            receiver.registration_id,
            ReceiverCmd(cmd=CMD_IDENTITY, args={
                "registration_id": receiver.registration_id,
            }),
        )
    except Exception as exc:
        log.warning(
            "cast_identity_send_failed",
            registration_id=receiver.registration_id, error=str(exc)[:160],
        )
    try:
        while True:
            raw = await websocket.receive_text()
            event = deserialise_event(raw)
            if event is None:
                # Tolerant of garbage — drop silently. Receivers might
                # be running newer schemas or buggy implementations;
                # one bad message shouldn't drop the connection.
                continue
            registry.record_event(receiver.registration_id, event)
            # Phase 4 telemetry-driven demotion. The TV shell relays the
            # loader's input_telemetry as a generic surface_event; feed it
            # to the demoter so a cheap-shim cast that isn't reaching the
            # game gets its profile stamped for promotion next cast.
            _maybe_feed_input_telemetry(websocket.app, user.id, event)
    except WebSocketDisconnect:
        pass
    except Exception as exc:
        log.warning(
            "cast_receiver_ws_error",
            registration_id=receiver.registration_id, error=str(exc)[:160],
        )
    finally:
        registry.detach(receiver.registration_id)


def _maybe_feed_input_telemetry(app: Any, user_id: str, event: Any) -> None:
    """Route a relayed ``input_telemetry`` surface_event to the demoter.

    The TV shell forwards the loader's ``augmentum.input_telemetry``
    postMessage as a generic ``surface_event`` whose ``data`` carries the
    telemetry fields (title_id, strategy, frames_received,
    unreachable_targets, window_ms). Fire-and-forget: a demotion is never
    on the WS critical path, and an absent demoter (non-sqlite backend)
    is a silent no-op.
    """
    if getattr(event, "event", "") != "surface_event":
        return
    data = getattr(event, "data", None) or {}
    if data.get("type") != "augmentum.input_telemetry":
        return
    demoter = getattr(app.state, "cast_telemetry_demoter", None)
    if demoter is None:
        return
    import asyncio
    try:
        asyncio.create_task(demoter.on_telemetry(user_id, data))
    except Exception as exc:
        log.warning("cast_telemetry_feed_failed", error=str(exc)[:160])


# Per-attachment slot cache so we only fire invite_slot_update when
# the slot transitions (not on every frame). Keyed by attachment_id;
# the WS handler's finally block evicts.
_last_known_slot: dict[str, int] = {}


async def _broadcast_invite_slot_update(
    app: Any, session_id: str, host_user_id: str,
) -> None:
    """Push the current player roster to every receiver the host has.

    Cheap and idempotent — receivers without an active invite overlay
    silently ignore the cmd. Failure is swallowed; an absent roster
    update isn't fatal to the input path.
    """
    registry = getattr(app.state, "cast_input_registry", None)
    rcv_registry = getattr(app.state, "receiver_registry", None)
    invite_store = getattr(app.state, "cast_invite_store", None)
    if registry is None or rcv_registry is None:
        return
    players = registry.roster_for_session(session_id)
    slots_remaining = 0
    if invite_store is not None:
        for r in invite_store.list_for_session(session_id):
            slots_remaining = max(slots_remaining, r.slots_remaining)
    try:
        from augmentum.cast.receiver_protocol import (
            CMD_INVITE_SLOT_UPDATE,
            ReceiverCmd,
        )
        await rcv_registry.broadcast(
            host_user_id,
            ReceiverCmd(
                cmd=CMD_INVITE_SLOT_UPDATE,
                args={
                    "session_id": session_id,
                    "players": players,
                    "slots_remaining": slots_remaining,
                },
            ),
        )
    except Exception as exc:
        log.debug(
            "cast_invite_slot_update_send_failed",
            session_id=session_id, error=str(exc)[:120],
        )


@router.websocket("/input/ws")
async def cast_input_ws(websocket: WebSocket) -> None:
    """WebSocket for cast-control input — phone-side producer.

    Query params:
      * ``session_id`` — the AGSP stream session this input targets.
        Required in production mode; relaxed in echo mode so the
        latency-spike page can connect without a live game.
      * ``pad_index`` — phone-local Gamepad API index (0..3). Used
        under the ``index`` slot strategy; ignored under
        ``firstpress`` until the first non-zero button frame claims
        a slot.
      * ``echo`` — when ``1``, the server echoes every received frame
        back with a server-side receive timestamp so the client can
        measure RTT. Used by ``/ui/cast-latency-test/``.

    Frame shape (client → server, JSON text):
        {"seq": int, "t_send": float_ms, "event": {...gamepad_state...}}
    Frame shape (server → client, echo mode only):
        {"seq": int, "t_send": float_ms, "t_recv": float_ms_server}
    Frame shape (server → client, production mode):
        {"kind": "rumble", "slot": int, "duration_ms": int,
         "strong": float, "weak": float}

    Production mode (echo=0): each frame is routed by
    :class:`augmentum.cast.input_bridge.CastInputRegistry` to the
    in-container ``cast-input-bridge.py`` daemon for the session.
    Rumble events flow back to the owning phone via the same registry.

    Auth: same cookie-based middleware as ``receiver_ws``. WS
    connections without auth close with 1008. The handler additionally
    verifies the session_id belongs to the calling user.
    """
    user = websocket.scope.get("user")
    if user is None:
        await websocket.close(code=1008, reason="auth required")
        return

    params = websocket.query_params
    session_id = (params.get("session_id") or "").strip()
    receiver_id = (params.get("receiver_id") or "").strip()
    echo_mode = (params.get("echo") or "").strip() == "1"
    try:
        pad_index = int(params.get("pad_index") or "0")
    except ValueError:
        pad_index = 0

    # Guest path: middleware resolved the invite token and stashed
    # the record on the scope. Pull the session_id from there and
    # skip the ownership check below — token possession IS the auth.
    # Guests can only join AGSP sessions; browser-cast is host-only.
    invite = websocket.scope.get("augmentum.cast.invite")
    is_guest_join = invite is not None
    if is_guest_join:
        session_id = invite.session_id
        receiver_id = ""  # guests never address a receiver directly

    # Three production targets, mutually exclusive:
    #   * receiver_id  → browser-cast (kiosk play surface on a TV)
    #   * session_id   → AGSP container (legacy / streamed games)
    #   * echo_mode    → latency-test loop, no real target
    is_browser_cast = bool(receiver_id) and not is_guest_join
    if not echo_mode and not session_id and not is_browser_cast:
        await websocket.close(
            code=1008,
            reason="session_id or receiver_id required outside echo mode",
        )
        return

    # Echo mode short-circuit. Pre-dates the production handler and
    # the latency-test page is the only consumer; no registry / no
    # session-ownership check needed.
    if echo_mode:
        await websocket.accept()
        log.info(
            "cast_input_ws_attached",
            user_id=user.id, session_id=session_id, echo=True,
        )
        try:
            while True:
                raw = await websocket.receive_text()
                try:
                    frame = json_loads(raw)
                except Exception:
                    continue
                if not isinstance(frame, dict):
                    continue
                t_recv = _ws_now_ms()
                await websocket.send_json({
                    "seq": frame.get("seq"),
                    "t_send": frame.get("t_send"),
                    "t_recv": t_recv,
                })
        except WebSocketDisconnect:
            pass
        except Exception as exc:
            log.warning(
                "cast_input_ws_echo_error",
                user_id=user.id, error=str(exc)[:160],
            )
        finally:
            log.info(
                "cast_input_ws_detached", user_id=user.id, echo=True,
            )
        return

    # Production mode.
    registry = getattr(websocket.app.state, "cast_input_registry", None)
    if registry is None:
        await websocket.close(code=1011, reason="cast input registry not initialised")
        return

    # Guest path: claim a slot off the invite token. If the token is
    # full / expired / revoked between middleware resolution and now,
    # claim() returns None and we reject before accepting the WS.
    guest_profile_id = ""
    guest_display_name = ""
    guest_color = ""
    if is_guest_join:
        invite_store = getattr(
            websocket.app.state, "cast_invite_store", None,
        )
        if invite_store is None:
            await websocket.close(code=1011, reason="invite store missing")
            return
        # Phase 2: read the optional profile id from the query string
        # (set by the guest-join page after the claim roundtrip).
        # Anonymous join still works for Phase 1 backward-compat.
        guest_profile_id = (params.get("guest_profile_id") or "").strip()
        if guest_profile_id:
            guest_store = getattr(websocket.app.state, "guest_store", None)
            if guest_store is not None:
                try:
                    profile = await guest_store.get(
                        guest_profile_id,
                        host_user_id=invite.host_user_id,
                    )
                except Exception:
                    profile = None
                if profile is None:
                    # The profile id doesn't belong to this host — refuse.
                    # Phase 1 anon path stays open via guest_profile_id="".
                    await websocket.close(
                        code=1008, reason="guest profile not at this host",
                    )
                    return
                guest_display_name = profile.get("display_name", "") or ""
                guest_color = profile.get("color", "") or ""
        claimed = invite_store.claim(
            invite.token, guest_profile_id=guest_profile_id,
        )
        if claimed is None:
            await websocket.close(code=1008, reason="invite full or expired")
            return
        # No additional session-ownership check — token possession
        # already proved the right to join this session.

    elif is_browser_cast:
        # Browser-cast path: validate the user owns the receiver, then
        # attach a phone whose target is the receiver's WS rather than
        # an AGSP container. No session ownership check (there's no
        # session — just a receiver loading a kiosk play surface).
        receiver_registry = getattr(
            websocket.app.state, "receiver_registry", None,
        )
        if receiver_registry is None:
            await websocket.close(
                code=1011, reason="cast receiver registry not initialised",
            )
            return
        receiver = receiver_registry.get(receiver_id)
        if receiver is None or receiver.user_id != user.id:
            await websocket.close(
                code=1008, reason="receiver not found or not yours",
            )
            return
    else:
        # Host path: session ownership check. Without this, a logged-in
        # user could connect to any session_id they happened to learn
        # and inject inputs into someone else's emulator.
        gs_runtime = getattr(websocket.app.state, "game_stream_runtime", None)
        if gs_runtime is not None:
            try:
                row = await gs_runtime._store.get_session(  # noqa: SLF001
                    session_id, user_id=user.id,
                )
            except Exception:
                row = None
            if row is None:
                await websocket.close(code=1008, reason="session not found or not yours")
                return

    await websocket.accept()
    log.info(
        "cast_input_ws_attached",
        user_id=user.id, session_id=session_id, echo=False,
        pad_index=pad_index, is_guest=is_guest_join,
        receiver_id=receiver_id if is_browser_cast else "",
    )
    phone = registry.attach_phone(
        ws=websocket, session_id=session_id, user_id=user.id,
        pad_index=pad_index,
        guest_profile_id=guest_profile_id,
        guest_display_name=guest_display_name,
        guest_color=guest_color,
        target_receiver_id=receiver_id if is_browser_cast else "",
    )

    if not is_browser_cast:
        await _broadcast_invite_slot_update(websocket.app, session_id, user.id)

    # Resolve receiver_registry once for the hot loop. None for the
    # legacy container path — route_input ignores it there.
    rr_for_loop = (
        getattr(websocket.app.state, "receiver_registry", None)
        if is_browser_cast else None
    )

    try:
        while True:
            raw = await websocket.receive_text()
            try:
                frame = json_loads(raw)
            except Exception:
                continue
            if not isinstance(frame, dict):
                continue
            forwarded = await registry.route_input(
                attachment_id=phone.attachment_id, frame=frame,
                receiver_registry=rr_for_loop,
            )
            # If route_input claimed a slot this frame, push the
            # updated roster to receivers so the player chips light up.
            # Browser-cast doesn't claim slots (single-pad-per-receiver)
            # so the roster broadcast is skipped on that branch.
            if (
                not is_browser_cast
                and forwarded
                and phone.slot != _last_known_slot.get(
                    phone.attachment_id, -1,
                )
            ):
                _last_known_slot[phone.attachment_id] = phone.slot
                await _broadcast_invite_slot_update(
                    websocket.app, session_id, user.id,
                )
    except WebSocketDisconnect:
        pass
    except Exception as exc:
        log.warning(
            "cast_input_ws_error",
            user_id=user.id, session_id=session_id, error=str(exc)[:160],
        )
    finally:
        _last_known_slot.pop(phone.attachment_id, None)
        await registry.detach_phone(phone.attachment_id)
        # Slot broadcast is AGSP-only; browser-cast has no slot roster.
        if not is_browser_cast:
            await _broadcast_invite_slot_update(
                websocket.app, session_id, user.id,
            )
        log.info(
            "cast_input_ws_detached",
            user_id=user.id, session_id=session_id,
            receiver_id=receiver_id if is_browser_cast else "",
        )


@router.websocket("/input/container-ws/{session_id}")
async def cast_input_container_ws(
    websocket: WebSocket, session_id: str,
) -> None:
    """WebSocket for the in-container ``cast-input-bridge.py`` daemon.

    Auth: ``?token=<x>`` query param validated against the session
    row's ``cast_input_token`` via :func:`hmac.compare_digest`. Mirrors
    the auth pattern of game-agent's bridge_ws — the token IS the
    credential because the container has no session cookie. Exempt
    from cookie middleware via ``/api/cast/input/container-ws/`` in
    ``_PUBLIC_PREFIXES``.

    Flow (after accept):
      1. Look up the session row + verify the token.
      2. Resolve ``pad_routing`` from the user's controller profile
         when ``system_id`` is on the row (default ``index``).
      3. Attach as a ``ConnectedContainer``.
      4. Read loop: inbound rumble frames are routed to the owning
         phone for that slot via ``CastInputRegistry.route_rumble``.
      5. On close, detach.
    """
    import hmac

    params = websocket.query_params
    token_param = (params.get("token") or "").strip()
    if not token_param:
        await websocket.close(code=1008, reason="token required")
        return

    gs_runtime = getattr(websocket.app.state, "game_stream_runtime", None)
    if gs_runtime is None:
        await websocket.close(code=1011, reason="game-stream runtime not initialised")
        return
    registry = getattr(websocket.app.state, "cast_input_registry", None)
    if registry is None:
        await websocket.close(code=1011, reason="cast input registry not initialised")
        return

    try:
        row = await gs_runtime._store.get_session(session_id)  # noqa: SLF001
    except Exception:
        row = None
    if not row:
        await websocket.close(code=1008, reason="no such session")
        return
    expected_token = row.get("cast_input_token") or ""
    if not expected_token or not hmac.compare_digest(expected_token, token_param):
        await websocket.close(code=1008, reason="bad token")
        return

    user_id = row.get("user_id") or ""
    pad_routing = "index"
    # Resolve per-user controller pad_routing when the session row
    # carries a system_id (emulator profiles). Non-emulator sessions
    # default to ``index`` — they don't have a system to look up.
    system_id_row = row.get("system_id") or ""
    controller_service = getattr(
        websocket.app.state, "controller_service", None,
    )
    if controller_service is not None and system_id_row:
        try:
            layout = await controller_service.resolve(
                user_id=user_id, system_id=system_id_row,
            )
            if layout is not None:
                pad_routing = layout.pad_routing
        except Exception:
            pad_routing = "index"

    await websocket.accept()
    container = registry.attach_container(
        ws=websocket, session_id=session_id, user_id=user_id,
        pad_routing=pad_routing, system_id=system_id_row,
    )

    try:
        while True:
            raw = await websocket.receive_text()
            try:
                frame = json_loads(raw)
            except Exception:
                continue
            if not isinstance(frame, dict):
                continue
            if frame.get("kind") == "rumble":
                await registry.route_rumble(
                    session_id=session_id, frame=frame,
                )
            # Other kinds (heartbeat, future stats) silently accepted.
    except WebSocketDisconnect:
        pass
    except Exception as exc:
        log.warning(
            "cast_input_container_ws_error",
            session_id=session_id, error=str(exc)[:160],
        )
    finally:
        registry.detach_container(container.session_id)


def _ws_now_ms() -> float:
    """Wall-clock millisecond timestamp matching JS ``Date.now() +
    performance.now() % 1`` precision. Used for echo timing comparisons
    against client-side performance.now().
    """
    import time as _t
    return _t.time() * 1000.0


def json_loads(raw: str):
    """Local thin import wrapper so the echo path doesn't pay the
    cost of resolving the json module name on every frame. ``orjson``
    is faster when present; stdlib json is the floor."""
    try:
        import orjson
        return orjson.loads(raw)
    except ImportError:
        import json
        return json.loads(raw)


