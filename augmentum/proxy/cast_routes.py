@router.get("/library/home")
async def cast_library_home(
    request: Request, trusted_id: str = "",
) -> dict[str, Any]:
    """Aggregated home-screen data for the cast surfaces.

    Powers BOTH /ui/cast-home/ (TV idle landing) and
    /ui/cast-control/ (phone/desktop remote). One endpoint, one
    shape — keeps the two surfaces in lockstep and lets the server
    own all kind/URL routing decisions.

    When ``trusted_id`` is provided and owned by the requesting user,
    the response is filtered by that receiver's ``rails_visible``
    prefs — sections the user disabled for that TV are omitted before
    any data fetch (no wasted file_index work for a rail that won't
    render). Empty/invalid/foreign trusted_id falls back to returning
    all sections so first-boot + unpaired callers still see content.

    Sections returned (in display order):

      ``resume``         — items with progress > 0 across audio + video
      ``recently_added`` — newly indexed across all media kinds
      ``audiobooks``     — recent audio entries
      ``movies``         — entity_kind=movie
      ``shows``          — entity_kind=series (drill-in for episodes)
      ``comics``         — recent comic entries
      ``gallery``        — recent image entries (companion's generated
                           images + chat-image uploads)

    Plus a flat ``libraries`` list (one entry per configured media
    server) so the controller can drill into per-library views.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    uid = user.id

    idx = getattr(request.app.state, "file_index", None)
    if idx is None:
        # Degraded mode — return empty shape so the surfaces render
        # their empty-state without breaking.
        return {"sections": [], "libraries": []}

    async def _build_section(*, slug: str, limit: int) -> dict[str, Any]:
        spec = _CAST_LIBRARY_SECTIONS.get(slug)
        if spec is None:
            return {"id": slug, "title": slug, "items": []}
        q = dict(spec["query"])
        # Comic rails are series-collapsed — fetch wider so we have
        # enough chapters to fill `limit` series groups even when one
        # series dominates the recent window. Same multiplier as the
        # paged section endpoint above.
        is_comic = q.get("kind") == "comic"
        # The Continue rail also collapses by series so users with
        # multiple mid-watched episodes of one show see ONE card.
        # Over-fetch 5x so the dedup has enough rows to fill ``limit``
        # distinct series even when one show dominates the tail.
        is_resume = slug == "resume"
        is_gallery = slug == "gallery"
        is_games = slug == "games"
        # Comics use the auto-sized fetch helper instead of a static
        # cap so libraries of any size surface every series. Gallery
        # gets the General-category helper (excludes backgrounds, never
        # surfaces private images on the home rail regardless of the
        # privacy setting — that's See-all-only). Other rails keep
        # their existing limit handling.
        items: list[dict[str, Any]] | None = None
        if is_comic:
            # Pull collapsed series straight from the cache when we
            # can — kills the 6 s, 20k-row fetch on every home poll.
            # The home rail picks a random `limit` from the full
            # series list, so we don't need the raw entries list at
            # all here.
            try:
                comic_series = await _get_collapsed_comic_series(
                    request, idx, uid,
                )
            except Exception as exc:
                log.warning("cast_library_section_failed", section=slug, error=str(exc))
                comic_series = []
            if len(comic_series) > limit:
                items = random.sample(comic_series, limit)
            else:
                items = list(comic_series)
                random.shuffle(items)
            entries = []
        elif is_gallery:
            db_conn = _app_db_conn(request)
            if db_conn is not None:
                try:
                    items, _ = await _fetch_gallery_tiles(
                        request, idx, db_conn, uid,
                        category="general", limit=limit, offset=0,
                    )
                except Exception as exc:
                    log.warning(
                        "cast_library_section_failed",
                        section=slug, error=str(exc),
                    )
                    items = []
            else:
                items = []
            entries = []
        elif is_games:
            try:
                items = await _fetch_game_tiles(
                    request, uid, limit=limit, offset=0,
                )
            except Exception as exc:
                log.warning(
                    "cast_library_section_failed",
                    section=slug, error=str(exc),
                )
                items = []
            entries = []
        else:
            if is_resume:
                q["limit"] = max(limit * 5, 60)
            else:
                q["limit"] = limit
            try:
                entries = await idx.list_recent(user_id=uid, **q)
            except Exception as exc:
                log.warning("cast_library_section_failed", section=slug, error=str(exc))
                entries = []
        if items is not None:
            # Already populated by a kind-specific branch above
            # (comic, gallery). The branches handle their own
            # sampling/filtering so the generic tile path skips them.
            pass
        elif is_resume:
            items = await _collapse_resume_by_series(
                entries, limit, idx=idx, user_id=uid,
            )
        else:
            items = [t for t in (_entry_to_tile(e) for e in entries) if t]
        return {"id": slug, "title": spec["title"], "items": items}

    # Per-receiver rail visibility. When trusted_id is supplied + owned
    # by this user, sections the user disabled for that TV are skipped
    # entirely (no file_index work for a rail that won't render).
    # Missing / foreign / revoked trusted_id falls through to "show
    # everything" — matches the pre-filter contract for callers that
    # haven't paired yet.
    hidden_slugs: set[str] = set()
    trusted_id = (trusted_id or "").strip()
    if trusted_id:
        trusted_store = getattr(request.app.state, "trusted_receiver_store", None)
        if trusted_store is not None:
            try:
                stored_prefs = await trusted_store.get_prefs(
                    trusted_id, user_id=uid,
                )
            except Exception as exc:
                log.warning(
                    "cast_library_home_prefs_lookup_failed",
                    trusted_id=trusted_id, error=str(exc),
                )
                stored_prefs = None
            if stored_prefs is not None:
                from augmentum.cast.receiver_prefs import with_defaults
                merged = with_defaults(stored_prefs)
                rails_visible = merged.get("rails_visible") or {}
                if isinstance(rails_visible, dict):
                    hidden_slugs = {
                        slug for slug, visible in rails_visible.items()
                        if visible is False
                    }

    sections: list[dict[str, Any]] = []
    for slug, spec in _CAST_LIBRARY_SECTIONS.items():
        if slug in hidden_slugs:
            continue
        sections.append(await _build_section(slug=slug, limit=int(spec["home_limit"])))
    # Drop empty sections from the response — keeps the rails on the
    # surfaces from showing skeletons for libraries the user hasn't
    # populated yet.
    sections = [s for s in sections if s["items"]]

    libraries: list[dict[str, Any]] = []
    media_store = getattr(request.app.state, "media_store", None)
    if media_store is not None:
        try:
            servers = await media_store.list_for_user(user_id=uid)
            for s in servers:
                libraries.append({
                    "id": s.id,
                    "name": s.name,
                    "provider": s.provider,
                })
        except Exception as exc:
            log.warning("cast_library_servers_failed", error=str(exc))

    return {
        "sections": sections,
        "libraries": libraries,
    }


class RenderStreamStartRequest(BaseModel):
    receiver_id: str
    # The URL the server-side Chromium will load. Anything reachable
    # from within the augmentum docker network — typically
    # ``https://augmentum:6443/ui/<surface>/?...``. The receiver never
    # sees this; it only iframes the resulting Selkies viewer URL.
    target_url: str
    # Slot on the receiver to mount the stream surface into. Defaults
    # to ``main`` because streamed surfaces are the primary content
    # for the casts that use them (VRM companion etc.).
    slot: str = SLOT_MAIN
    # Optional bitrate/resolution overrides; otherwise the profile
    # defaults apply (1920x1080 @ 6 Mbps).
    bitrate_mbps: int | None = None
    resolution: str | None = None


@router.post("/render-stream/start")
async def cast_render_stream_start(
    request: Request,
    body: RenderStreamStartRequest,
) -> dict[str, Any]:
    """Spawn a server-side browser-stream session and cast its
    Selkies viewer URL to the receiver in one atomic flow.

    This is the cheap streaming primitive: anything web-rendered that
    can't run on the TV (VRM companion on a budget Mali GPU, comic
    reader, notebook, browse panel) gets rendered on the server's
    Chromium + streamed via WebRTC. The receiver just iframes the
    Selkies viewer — no bespoke WebRTC code on the TV side.

    On success:
      * Reserves a stream container session via GameStreamRuntime
        with the ``browser-stream`` profile.
      * Builds the proxied stream URL (``/stream/<port>/`` so it
        flows through Augmentum's HTTPS edge — needed because the
        TV's WebView only trusts the configured Augmentum host).
      * Sends a ``surface_open`` cmd over the cast WS so the receiver
        iframes the stream URL.
      * Records the cast event for audit.

    Returns the session id + stream URL so the caller can show
    "now showing: streamed surface" + later issue a stop.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    if not body.target_url:
        raise HTTPException(422, "target_url required")
    if not is_valid_slot(body.slot):
        raise HTTPException(
            422, f"unknown slot {body.slot!r}; valid: {', '.join(SLOTS)}",
        )

    registry = getattr(request.app.state, "receiver_registry", None)
    if registry is None:
        raise HTTPException(503, "receiver registry not initialised")
    runtime = getattr(request.app.state, "game_stream_runtime", None)
    if runtime is None:
        raise HTTPException(
            503,
            "stream runtime not enabled — set "
            "AUGMENTUM_GAME_STREAM_ENABLED=true and use compose.game-stream.yaml",
        )

    receiver = registry.get(body.receiver_id)
    if receiver is None or receiver.user_id != user.id:
        raise HTTPException(404, "receiver not connected or not owned by you")

    # Resolve the target URL into something the container's Chrome
    # can actually fetch. Streamed containers run on the default
    # docker bridge — they can't reach the augmentum service by name
    # across networks. ``host.docker.internal`` gives them a route
    # back to the host's Caddy edge (same pattern game_stream uses
    # for its reverse-proxy probe). Absolute URLs are passed through
    # so callers can target external hosts when that's intended.
    raw_target = body.target_url.strip()
    if raw_target.startswith(("http://", "https://")):
        absolute_target = raw_target
    else:
        from augmentum.proxy.game_stream_routes import _stream_probe_host
        # Augmentum's HTTPS edge port. Pulled from settings so a
        # non-default deployment routes correctly.
        from augmentum.config import settings as _settings
        edge_port = int(getattr(_settings, "https_port", 6443) or 6443)
        if not raw_target.startswith("/"):
            raw_target = "/" + raw_target
        absolute_target = f"https://{_stream_probe_host()}:{edge_port}{raw_target}"

    # Mint a real auth session for the rendering container's Chrome,
    # then wrap the target URL in a one-shot redeem endpoint. The
    # rendering Chrome lands on /api/cast/stream-auth/redeem, the
    # endpoint validates the redeem token, returns a Set-Cookie +
    # 302 → target, Chrome follows and now carries the user's session
    # for every subsequent /api call inside the rendering surface.
    # Without this every /api call from the surface returns 401 and
    # cast-vrm (etc.) can't resolve the user's avatar / settings /
    # voice session — i.e. exactly the symptom we were chasing.
    sm = getattr(request.app.state, "session_manager", None)
    redeem_store = getattr(request.app.state, "stream_auth_redeem_store", None)
    if sm is not None and redeem_store is not None:
        raw_session = await sm.create_session(
            user.id,
            ip_address="(stream-render)",
            user_agent="AugmentumStreamBrowser/1.0",
            source="cast_render",
        )
        from urllib.parse import quote
        redeem_token = redeem_store.mint(
            session_token=raw_session, user_id=user.id, next_url=absolute_target,
        )
        from augmentum.proxy.game_stream_routes import _stream_probe_host
        from augmentum.config import settings as _settings
        edge_port = int(getattr(_settings, "https_port", 6443) or 6443)
        absolute_target = (
            f"https://{_stream_probe_host()}:{edge_port}"
            f"/api/cast/stream-auth/redeem?t={quote(redeem_token)}"
        )
    else:
        log.warning(
            "cast_render_stream_no_redeem_store",
            note="rendering Chrome will hit auth-required endpoints unauthenticated",
        )

    # Start the browser-stream session. ``target_url`` rides on the
    # world_settings_override so the docker adapter forwards it as
    # AUGMENTUM_TARGET_URL — the only profile-specific knob the
    # entrypoint reads.
    try:
        info = await runtime.start_session(
            user_id=user.id,
            profile_id="browser-stream",
            world_id=None,
            bitrate_mbps=body.bitrate_mbps,
            resolution=body.resolution,
            world_settings_override={"target_url": absolute_target},
        )
    except Exception as exc:
        # The runtime layer raises strings like "no streaming ports
        # available", "image not built", "GPU missing". Pass through.
        raise HTTPException(502, str(exc) or "stream session start failed") from exc

    # Build the stream URL the TV will iframe. Use the same proxied-
    # path pattern game_stream_routes uses — selkies' viewer is served
    # off /stream/<port>/ via the augmentum HTTPS edge.
    stream_path = f"/stream/{info.stream_port}/"

    sid = await _cast_surface(
        registry, body.receiver_id,
        surface_kind=SURFACE_STREAM,
        surface_url=stream_path,
        slot=body.slot,
        state={
            "target_url": body.target_url,
            "stream_session_id": info.session_id,
        },
    )
    if sid is None:
        # Receiver dropped between port reserve and surface_open — we
        # already have a container running with nobody to view it.
        # Stop it before raising so the caller's retry doesn't pile up
        # orphan containers.
        try:
            await runtime.stop_session(
                info.session_id, user_id=user.id, reason="cast_send_failed",
            )
        except Exception as exc:
            log.warning(
                "cast_render_stream_orphan_cleanup_failed",
                stream_session_id=info.session_id, error=str(exc),
            )
        raise HTTPException(502, "receiver send failed (connection dropped?)")

    # Register the linkage so detach() and surface_closed reap the
    # render container. Without this the agsp-* container survives
    # every disconnect path.
    registry.note_stream_session(body.receiver_id, sid, info.session_id)

    # Audit + trusted bookkeeping (fire-and-forget, mirrors /send).
    event_store = getattr(request.app.state, "cast_event_store", None)
    trusted_store = getattr(request.app.state, "trusted_receiver_store", None)
    if event_store is not None:
        try:
            await event_store.record_start(
                user_id=user.id,
                trusted_id=receiver.trusted_id,
                registration_id=body.receiver_id,
                surface_id=sid,
                surface_kind=SURFACE_STREAM,
                surface_url=stream_path,
                slot=body.slot,
            )
        except Exception as exc:
            log.warning("cast_event_record_start_failed", error=str(exc))
    if trusted_store is not None and receiver.trusted_id:
        try:
            await trusted_store.mark_cast(receiver.trusted_id, user_id=user.id)
        except Exception as exc:
            log.warning("trusted_receiver_mark_cast_failed", error=str(exc))

    return {
        "surface_id": sid,
        "receiver_id": body.receiver_id,
        "slot": body.slot,
        "stream_session_id": info.session_id,
        "stream_path": stream_path,
        "target_url": body.target_url,
    }


class GameCastStartRequest(BaseModel):
    """Body for POST /api/cast/games/{title_id}/start.

    Cast a game tile from the controller's games rail to a receiver.
    The endpoint spawns the AGSP container via TitleService.launch
    (which handles BIOS checks, profile resolution, run telemetry)
    and casts the Selkies viewer URL as a SURFACE_STREAM in one call.
    """
    receiver_id: str
    slot: str = SLOT_MAIN
    bitrate_mbps: int | None = None
    resolution: str | None = None
    encoder: str | None = None


@router.post("/games/{title_id}/start")
async def cast_game_start(
    title_id: str, request: Request, body: GameCastStartRequest,
) -> dict[str, Any]:
    """Launch a streamable game on the AGSP runtime and cast it to a TV.

    Composes ``TitleService.launch(prefer_runtime="agsp-streamed")`` with
    the cast-surface dispatch path used by ``/render-stream/start``.
    Three failure modes the controller cares about:

      * 404 — no such title for this user
      * 409 — title isn't streamable (no streaming runtime, or BIOS
        files missing). Message carries the user-actionable hint.
      * 502 — receiver dropped between launch + surface_open; the
        runtime session is cleaned up before raising so the controller
        can safely retry.

    On success the call is registered with
    ``receiver_registry.note_stream_session`` so the disconnect-reap
    hook tears the container down when the TV drops, matching the
    invariants render-stream sessions follow.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    if not is_valid_slot(body.slot):
        raise HTTPException(
            422, f"unknown slot {body.slot!r}; valid: {', '.join(SLOTS)}",
        )

    registry = getattr(request.app.state, "receiver_registry", None)
    if registry is None:
        raise HTTPException(503, "receiver registry not initialised")
    title_service = getattr(request.app.state, "title_service", None)
    if title_service is None:
        raise HTTPException(
            503,
            "title service not initialised — AGSP/title runtime not enabled",
        )

    receiver = registry.get(body.receiver_id)
    if receiver is None or receiver.user_id != user.id:
        raise HTTPException(404, "receiver not connected or not owned by you")

    # Compose the launch context. Bitrate / resolution / encoder are
    # plumbed through to runtime.start_session via AgspStreamedRuntime
    # exactly the way render-stream/start does. None values let the
    # profile defaults apply.
    ctx: dict[str, Any] = {"user_id": user.id}
    if body.bitrate_mbps is not None:
        ctx["bitrate_mbps"] = body.bitrate_mbps
    if body.resolution is not None:
        ctx["resolution"] = body.resolution
    if body.encoder is not None:
        ctx["encoder"] = body.encoder

    from augmentum.titles import (
        TitleNotFound,
        TitleNotPlayable,
        TitleServiceError,
    )
    try:
        launched = await title_service.launch(
            title_id, user_id=user.id,
            ctx=ctx, prefer_runtime="agsp-streamed",
        )
    except TitleNotFound as exc:
        raise HTTPException(404, str(exc)) from exc
    except TitleNotPlayable as exc:
        # BIOS-missing + core-unavailable land here. The message carries
        # the actionable hint (e.g. "missing BIOS files X, Y; upload at
        # /api/titles/bios/{system_id}/").
        raise HTTPException(409, str(exc)) from exc
    except TitleServiceError as exc:
        raise HTTPException(400, str(exc)) from exc

    handle = launched.get("handle") or {}
    run_id = launched.get("run_id") or ""
    if handle.get("kind") != "webrtc":
        # The title resolved to a non-streaming runtime (browser-iframe,
        # emulator-browser, …). Those aren't TV-castable as a stream —
        # the controller should fall back to the in-app player. Clean
        # up the run row we already opened so it doesn't dangle.
        runtime_id = handle.get("runtime_id") or ""
        session_id = handle.get("session_id") or ""
        try:
            await title_service.end_run(
                run_id, user_id=user.id,
                runtime_id=runtime_id, session_id=session_id,
                exit_reason="not_streamable_for_cast",
            )
        except Exception as exc:
            log.warning(
                "cast_game_non_streaming_cleanup_failed",
                run_id=run_id, error=str(exc),
            )
        raise HTTPException(
            422,
            f"title resolved to non-streaming runtime "
            f"{handle.get('runtime_id')!r} — not castable",
        )

    stream_port = (handle.get("metadata") or {}).get("stream_port")
    session_id = handle.get("session_id") or ""
    if not stream_port or not session_id:
        raise HTTPException(
            502,
            "runtime returned an incomplete handle "
            "(missing stream_port or session_id)",
        )
    stream_path = f"/stream/{stream_port}/"

    sid = await _cast_surface(
        registry, body.receiver_id,
        surface_kind=SURFACE_STREAM,
        surface_url=stream_path,
        slot=body.slot,
        state={
            "title_id": title_id,
            "title": (launched.get("manifest") or {}).get("title", ""),
            "stream_session_id": session_id,
            "run_id": run_id,
        },
    )
    if sid is None:
        # Receiver dropped between launch and surface_open — same
        # cleanup pattern as render-stream/start so a retry doesn't
        # pile up orphan containers + open title_runs rows.
        try:
            await title_service.end_run(
                run_id, user_id=user.id,
                runtime_id=handle.get("runtime_id") or "",
                session_id=session_id,
                exit_reason="cast_send_failed",
            )
        except Exception as exc:
            log.warning(
                "cast_game_orphan_cleanup_failed",
                run_id=run_id, session_id=session_id, error=str(exc),
            )
        raise HTTPException(502, "receiver send failed (connection dropped?)")

    # Register the linkage so detach() + surface_closed reap the
    # AGSP container if the TV WS drops. Same reap hook every
    # render-stream session uses; nothing game-specific here.
    registry.note_stream_session(body.receiver_id, sid, session_id)

    # Audit + trusted bookkeeping — fire-and-forget to keep cast
    # latency tight (mirrors /send + /render-stream/start).
    event_store = getattr(request.app.state, "cast_event_store", None)
    trusted_store = getattr(request.app.state, "trusted_receiver_store", None)
    if event_store is not None:
        try:
            await event_store.record_start(
                user_id=user.id,
                trusted_id=receiver.trusted_id,
                registration_id=body.receiver_id,
                surface_id=sid,
                surface_kind=SURFACE_STREAM,
                surface_url=stream_path,
                slot=body.slot,
            )
        except Exception as exc:
            log.warning("cast_event_record_start_failed", error=str(exc))
    if trusted_store is not None and receiver.trusted_id:
        try:
            await trusted_store.mark_cast(receiver.trusted_id, user_id=user.id)
        except Exception as exc:
            log.warning("trusted_receiver_mark_cast_failed", error=str(exc))

    # Resolve max_players via the runtime's session row so the
    # controller knows whether the "+ Players" couch-coop button
    # should appear. Best-effort — failure here doesn't block the
    # cast itself.
    max_players = 1
    try:
        gs_runtime = getattr(request.app.state, "game_stream_runtime", None)
        if gs_runtime is not None:
            row = await gs_runtime._store.get_session(  # noqa: SLF001
                session_id, user_id=user.id,
            )
            if row:
                from augmentum.game_stream.profiles import (
                    profile_registry as _profiles,
                )
                profile = _profiles.get(row.get("profile_id") or "")
                max_players = int(getattr(profile, "max_players", 1) or 1)
    except Exception as exc:
        log.debug("cast_game_max_players_lookup_failed", error=str(exc))

    return {
        "surface_id": sid,
        "receiver_id": body.receiver_id,
        "slot": body.slot,
        "stream_session_id": session_id,
        "stream_path": stream_path,
        "title_id": title_id,
        "run_id": run_id,
        "max_players": max_players,
    }


class InviteCreateRequest(BaseModel):
    """Body for POST /api/cast/games/session/{session_id}/invite.

    Host mints a short-TTL token that admits ``max_slots`` guests via
    the cast-guest-join page. ``receiver_id`` identifies which TV
    should display the QR overlay.
    """
    receiver_id: str
    max_slots: int = 3
    ttl_seconds: int | None = None


@router.post("/games/session/{session_id}/invite")
async def cast_game_invite(
    session_id: str, request: Request, body: InviteCreateRequest,
) -> dict[str, Any]:
    """Mint a couch co-op invite token for an active streaming session.

    Phase 1 (anonymous join): the returned token grants temporary
    "open the controller WS for this session" auth to any phone that
    holds it. Slot counter on the token prevents over-claim. Token TTL
    defaults to ``cast_invite_default_ttl_seconds`` (300s).

    Returns 404 when the session isn't owned by the caller. Returns
    409 when the game profile's ``max_players`` is 1 (single-player —
    nothing to invite to).
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")

    invite_store = getattr(request.app.state, "cast_invite_store", None)
    if invite_store is None:
        raise HTTPException(503, "invite store not initialised")
    gs_runtime = getattr(request.app.state, "game_stream_runtime", None)
    if gs_runtime is None:
        raise HTTPException(503, "game-stream runtime not initialised")
    registry = getattr(request.app.state, "receiver_registry", None)
    if registry is None:
        raise HTTPException(503, "receiver registry not initialised")

    row = await gs_runtime._store.get_session(  # noqa: SLF001
        session_id, user_id=user.id,
    )
    if row is None:
        raise HTTPException(404, "session not found or not yours")

    # Block invite on single-player profiles. The "+ Players" chip
    # should be hidden in the UI for these, but a malicious caller
    # could POST directly — defence-in-depth.
    from augmentum.game_stream.profiles import profile_registry as _profiles
    profile = _profiles.get(row.get("profile_id") or "")
    max_players = int(getattr(profile, "max_players", 1) or 1)
    if max_players <= 1:
        raise HTTPException(
            409, "this game's profile is single-player (max_players=1)",
        )

    # Receiver must be the same user's. Mirror of cast_game_start's
    # ownership check — prevents inviting on someone else's TV.
    receiver = registry.get(body.receiver_id)
    if receiver is None or receiver.user_id != user.id:
        raise HTTPException(
            404, "receiver not connected or not owned by you",
        )

    # The host already holds one slot (P1), so the invite admits at
    # most max_players - 1 guests. Honour the caller's cap as a
    # ceiling, not a floor.
    available = max(0, max_players - 1)
    if available <= 0:
        raise HTTPException(409, "all player slots already claimed")
    slots = min(int(body.max_slots or 3), available)

    # Resolve TTL from settings, capped by the caller's optional
    # ttl_seconds (caller can shrink but not extend the default).
    settings_obj = getattr(request.app.state, "settings", None)
    default_ttl = 300
    if settings_obj is not None:
        default_ttl = int(
            getattr(settings_obj, "cast_invite_default_ttl_seconds", 300)
            or 300
        )
    ttl = (
        min(int(body.ttl_seconds), default_ttl)
        if body.ttl_seconds and body.ttl_seconds > 0
        else default_ttl
    )

    record = invite_store.mint(
        session_id=session_id, host_user_id=user.id,
        max_slots=slots, ttl_s=ttl,
    )

    join_url = _build_join_url(request, record.token)
    qr_url = f"/api/cast/invite/qr/{record.token}.svg"

    # Dispatch the overlay command to the TV. Failure to send is not
    # fatal — the token is still live, the host's UI just won't show
    # a QR on that particular receiver (perhaps the receiver dropped
    # between mint and send).
    from augmentum.cast.receiver_protocol import (
        CMD_SHOW_INVITE_QR,
        ReceiverCmd,
    )
    cmd = ReceiverCmd(
        cmd=CMD_SHOW_INVITE_QR,
        args={
            "token": record.token,
            "join_url": join_url,
            "qr_url": qr_url,
            "slots_remaining": record.slots_remaining,
            "slots_total": slots,
            "expires_at": record.expires_at,
        },
    )
    try:
        await registry.send(body.receiver_id, cmd)
    except Exception as exc:
        log.warning(
            "cast_invite_cmd_send_failed",
            session_id=session_id, receiver_id=body.receiver_id,
            error=str(exc)[:160],
        )

    log.info(
        "cast_invite_created",
        session_id=session_id, user_id=user.id,
        receiver_id=body.receiver_id,
        token_prefix=record.token[:12], slots=slots, ttl_s=ttl,
    )

    return {
        "token": record.token,
        "join_url": join_url,
        "qr_url": qr_url,
        "expires_at": record.expires_at,
        "slots_remaining": record.slots_remaining,
        "slots_total": slots,
    }


@router.post("/games/session/{session_id}/invite/{token}/revoke")
async def cast_game_invite_revoke(
    session_id: str, token: str, request: Request,
) -> dict[str, Any]:
    """Cancel an invite. Idempotent — revoking an unknown/expired
    token returns success (the caller's intent is satisfied either way).

    Already-joined guests remain connected; only future joins are
    blocked. Dispatches ``hide_invite_qr`` to the receiver that holds
    the overlay so the QR disappears on the TV.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    invite_store = getattr(request.app.state, "cast_invite_store", None)
    if invite_store is None:
        raise HTTPException(503, "invite store not initialised")
    registry = getattr(request.app.state, "receiver_registry", None)

    record = invite_store.get(token)
    receiver_id = ""
    if record is not None and record.session_id != session_id:
        raise HTTPException(404, "token does not match session")

    invite_store.revoke(token, host_user_id=user.id)

    # Best-effort: broadcast hide to every receiver the user has, so
    # a stale overlay can't outlive the token even if the original
    # receiver_id is lost. Cheap and idempotent on the receiver side.
    if registry is not None:
        from augmentum.cast.receiver_protocol import (
            CMD_HIDE_INVITE_QR,
            ReceiverCmd,
        )
        cmd = ReceiverCmd(
            cmd=CMD_HIDE_INVITE_QR,
            args={"token": token, "reason": "revoked"},
        )
        try:
            await registry.broadcast(user.id, cmd)
        except Exception as exc:
            log.warning(
                "cast_invite_hide_broadcast_failed",
                user_id=user.id, token_prefix=token[:12],
                error=str(exc)[:160],
            )

    log.info(
        "cast_invite_revoked_by_host",
        session_id=session_id, user_id=user.id,
        token_prefix=token[:12], receiver_id=receiver_id,
    )
    return {"token": token, "revoked": True}


class GuestIdentifyRequest(BaseModel):
    """Body for POST /api/cast/guest/identify.

    The invite token scopes the call to one host's data. ``device_uuid``
    and ``ua_hash`` are the Phase 3 fingerprint inputs (no-op in Phase 2
    code paths but accepted so the wire shape stays stable across
    phase boundaries).
    """
    token: str
    device_uuid: str = ""
    ua_hash: str = ""


@router.post("/guest/identify")
async def cast_guest_identify(
    request: Request, body: GuestIdentifyRequest,
) -> dict[str, Any]:
    """Resolve an invite token to the host's guest roster.

    Public — no Augmentum auth required. The token in the body IS the
    credential; possession scopes this call to the matching host's
    data. Returns the recent guest profiles so a returning guest can
    pick themselves rather than retyping their name.

    Phase 3 extension: if ``device_uuid`` matches a known guest_device
    row, return ``matched=true`` + the profile so the page can skip
    the picker entirely. Phase 2 always returns ``matched=false`` and
    the existing-profiles list.
    """
    invite_store = getattr(request.app.state, "cast_invite_store", None)
    guest_store = getattr(request.app.state, "guest_store", None)
    if invite_store is None or guest_store is None:
        raise HTTPException(503, "guest substrate not initialised")

    record = invite_store.get(body.token)
    if record is None:
        raise HTTPException(404, "invite not found or expired")

    profiles = await guest_store.list_for_host(
        host_user_id=record.host_user_id, limit=8,
    )

    # Phase 3 hook: device-fingerprint lookup goes here. Returns a
    # specific matched profile when the device has joined before.
    matched_profile = None
    if body.device_uuid:
        device_store = getattr(request.app.state, "guest_device_store", None)
        if device_store is not None:
            matched_profile = await device_store.match(
                host_user_id=record.host_user_id,
                device_uuid=body.device_uuid,
                ua_hash=body.ua_hash,
            )

    response: dict[str, Any] = {
        "matched": matched_profile is not None,
        "host_label": "",  # filled when receiver label persistence lands
        "existing_profiles": [
            {
                "id": p["id"],
                "display_name": p["display_name"],
                "color": p.get("color", ""),
            }
            for p in profiles
        ],
    }
    if matched_profile is not None:
        response["profile"] = {
            "id": matched_profile["id"],
            "display_name": matched_profile["display_name"],
            "color": matched_profile.get("color", ""),
        }
    return response


class GuestClaimRequest(BaseModel):
    """Body for POST /api/cast/guest/claim.

    Either ``profile_id`` (existing) or ``new_name`` (mint) must be
    set. ``device_uuid`` + ``ua_hash`` are recorded against the
    resolved profile in Phase 3 — Phase 2 ignores them.
    """
    token: str
    profile_id: str = ""
    new_name: str = ""
    device_uuid: str = ""
    ua_hash: str = ""


@router.post("/guest/claim")
async def cast_guest_claim(
    request: Request, body: GuestClaimRequest,
) -> dict[str, Any]:
    """Create-or-resolve a guest profile and return its id.

    The guest-join page calls this after the user picks an existing
    profile or types a new name. The returned ``profile_id`` is then
    passed as a query param when opening the controller WS so the
    registry can stamp it on the phone's attachment.

    Returns 409 when the name collides with an existing profile —
    the response carries the existing profile's id so the UI can
    fall back to "is that you?" without a second roundtrip.
    """
    invite_store = getattr(request.app.state, "cast_invite_store", None)
    guest_store = getattr(request.app.state, "guest_store", None)
    if invite_store is None or guest_store is None:
        raise HTTPException(503, "guest substrate not initialised")

    record = invite_store.get(body.token)
    if record is None:
        raise HTTPException(404, "invite not found or expired")

    profile = None
    if body.profile_id:
        profile = await guest_store.get(
            body.profile_id, host_user_id=record.host_user_id,
        )
        if profile is None:
            raise HTTPException(404, "profile not found at this host")
    elif body.new_name:
        clean = body.new_name.strip()
        if not clean:
            raise HTTPException(400, "name cannot be empty")
        # Mint, falling back to "is that you?" on collision.
        try:
            profile = await guest_store.create_profile(
                host_user_id=record.host_user_id, display_name=clean,
            )
        except Exception:
            existing = await guest_store.get_by_name(
                host_user_id=record.host_user_id, display_name=clean,
            )
            if existing is None:
                raise HTTPException(400, "name in use; pick another") from None
            return {
                "conflict": True,
                "existing_profile": {
                    "id": existing["id"],
                    "display_name": existing["display_name"],
                    "color": existing.get("color", ""),
                },
            }
    else:
        raise HTTPException(400, "profile_id or new_name required")

    # Phase 3 hook: record the device fingerprint against this profile.
    if body.device_uuid:
        device_store = getattr(request.app.state, "guest_device_store", None)
        if device_store is not None:
            try:
                await device_store.link_device(
                    guest_profile_id=profile["id"],
                    host_user_id=record.host_user_id,
                    device_uuid=body.device_uuid,
                    ua_hash=body.ua_hash,
                )
            except Exception as exc:
                log.warning(
                    "cast_guest_device_link_failed",
                    profile_id=profile["id"], error=str(exc),
                )

    # Bump last_seen so the picker order reflects "most recent first."
    await guest_store.touch_last_seen(
        profile["id"], host_user_id=record.host_user_id,
        increment_play_count=True,
    )

    # Phase 4 observation hook: emit a signal_events row so the
    # companion sees recurring guests in its social-graph signal feed
    # ("alice visits weekly"). Fingerprint is the guest_profile_id so
    # repeat visits collapse onto one row with bumping occurrence_count.
    await _emit_guest_visit_signal(
        request.app, host_user_id=record.host_user_id,
        profile=profile, session_id=record.session_id,
    )

    return {
        "profile": {
            "id": profile["id"],
            "display_name": profile["display_name"],
            "color": profile.get("color", ""),
        },
    }


async def _emit_guest_visit_signal(
    app: Any, *, host_user_id: str, profile: dict[str, Any],
    session_id: str,
) -> None:
    """Insert-or-bump a ``guest_visit`` row in signal_events.

    Cross-modal hook — the companion's observation substrate
    surfaces these as "Frequent guests" signals; future host-side UI
    can summarise "alice last visited 4 days ago, total 12 sessions."
    Best-effort: SQL errors swallowed since the cast path mustn't
    fail because of an observation write.
    """
    try:
        sm = getattr(app.state, "state_manager", None)
        backend = getattr(sm, "backend", None) if sm is not None else None
        conn = getattr(backend, "conn", None)
        if conn is None:
            return
        import secrets as _secrets
        import time as _time
        now = int(_time.time())
        fingerprint = f"guest_visit:{profile['id']}"
        details = (
            '{"guest_profile_id":"%s","display_name":"%s",'
            '"session_id":"%s","host_user_id":"%s"}'
            % (
                profile["id"],
                profile["display_name"].replace('"', "'"),
                session_id, host_user_id,
            )
        )
        # UPSERT shape: try insert; on conflict bump occurrence_count
        # + refresh last_seen_at + details_json.
        await conn.execute(
            """INSERT INTO signal_events
               (id, user_id, source, category, fingerprint, summary,
                details_json, first_seen_at, last_seen_at,
                occurrence_count, status)
               VALUES (?, ?, 'cast_couch_coop', 'social', ?,
                       ?, ?, ?, ?, 1, 'open')
               ON CONFLICT(user_id, source, fingerprint) DO UPDATE SET
                 last_seen_at = excluded.last_seen_at,
                 occurrence_count = occurrence_count + 1,
                 details_json = excluded.details_json,
                 status = 'open'""",
            (
                f"sig_{_secrets.token_hex(6)}",
                host_user_id,
                fingerprint,
                f"Guest visit: {profile['display_name']}",
                details,
                now, now,
            ),
        )
        await conn.commit()
    except Exception as exc:
        log.debug(
            "cast_guest_visit_signal_emit_failed",
            host_user_id=host_user_id, error=str(exc)[:120],
        )


