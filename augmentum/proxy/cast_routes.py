@pair_router.get("/qr/{pair_code}.svg")
async def pair_qr(pair_code: str, request: Request) -> Response:
    """Serve the QR for a pair code as an SVG. Anyone with the code
    can fetch the SVG (it's the same code the QR encodes). Generated
    on demand — no caching beyond the pair record's TTL."""
    store = getattr(request.app.state, "pair_store", None)
    if store is None:
        raise HTTPException(503, "pair store not initialised")
    record = store.poll(pair_code)
    if record is None or record.state not in (STATE_PENDING, STATE_APPROVED):
        raise HTTPException(404, "pair code not found or expired")

    pair_url = _build_pair_url(request, pair_code)

    try:
        import qrcode
        import qrcode.image.svg
        factory = qrcode.image.svg.SvgPathImage
        img = qrcode.make(pair_url, image_factory=factory, box_size=14, border=2)
        from io import BytesIO
        buf = BytesIO()
        img.save(buf)
        svg_bytes = buf.getvalue()
    except Exception as exc:
        log.warning("cast_pair_qr_generate_failed", error=str(exc))
        raise HTTPException(500, "qr generation failed") from exc

    return Response(
        content=svg_bytes,
        media_type="image/svg+xml",
        headers={"Cache-Control": "no-store"},
    )


