@router.post("/trusted-receivers/{trusted_id}/revoke")
async def revoke_trusted_receiver(trusted_id: str, request: Request) -> dict[str, Any]:
    """Revoke a trusted receiver. Future connects from that device
    are rejected; any currently-connected WS gets closed."""
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    store = getattr(request.app.state, "trusted_receiver_store", None)
    if store is None:
        raise HTTPException(503, "trusted-receiver store not initialised")
    if not await store.revoke(trusted_id, user_id=user.id):
        raise HTTPException(404, "trusted receiver not found or already revoked")

    # Close any live WS sessions for this trusted_id.
    registry = getattr(request.app.state, "receiver_registry", None)
    closed_count = 0
    if registry is not None:
        for conn in list(registry.list_for_user(user.id)):
            if conn.trusted_id == trusted_id:
                try:
                    await conn.ws.close(code=4003, reason="receiver revoked")
                except Exception:
                    log.debug("cast_revoke_ws_close_failed", exc_info=True)
                registry.detach(conn.registration_id)
                closed_count += 1
    return {"revoked": True, "trusted_id": trusted_id, "closed_connections": closed_count}


