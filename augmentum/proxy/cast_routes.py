# ── Gallery category dispatch ────────────────────────────────────
# The gallery surfaces three logical folders, only one of which the
# generic ``kind='image'`` file_index query reaches cleanly:
#
#   General      — public images that aren't backgrounds (default)
#   Backgrounds  — generations marked as scene backgrounds
#   Private      — generations marked private (NOT in file_index by
#                  design — set_private unregisters them so the Files
#                  panel and global search stay safe). Gated by the
#                  ``cast_gallery_show_private`` setting.
#
# Private images bypass file_index entirely and read from
# image_generations directly; the tile shape is synthesised because
# there's no FileEntry to feed _entry_to_tile.

VALID_GALLERY_CATEGORIES = {"general", "backgrounds", "private"}


async def _image_gen_flag_map(db, user_id: str) -> dict[str, tuple[bool, bool]]:
    """Return image_id → (is_private, is_background) for the user.

    Used to filter the file_index image rows by background flag (which
    only lives on image_generations) without an N+1 query."""
    cursor = await db.execute(
        "SELECT image_id, COALESCE(is_private, 0), COALESCE(is_background, 0) "
        "FROM image_generations WHERE user_id = ?",
        (user_id,),
    )
    return {row[0]: (bool(row[1]), bool(row[2])) for row in await cursor.fetchall()}


def _private_image_to_tile(row, user_id: str) -> dict[str, Any]:
    """Build a tile for a private image_generations row.

    No file_index entry exists for these (private images are
    unregistered to keep the file_index privacy invariant). Cast URL
    routes through /api/image/{image_id}, which serves directly from
    image_generations with the auth user check.
    """
    image_id = row[0]
    prompt = (row[1] or "").strip()
    model = row[2] or ""
    width = row[3] or 0
    height = row[4] or 0
    created_at = row[5] or ""
    title = prompt[:60] if prompt else "Private image"
    sub_bits = []
    if model:
        sub_bits.append(model)
    if width and height:
        sub_bits.append(f"{width}×{height}")
    return {
        "file_id": image_id,
        "title": title,
        "subtitle": " · ".join(sub_bits),
        "kind": "image",
        "entity_kind": "",
        "source": "images",
        "cover_url": f"/api/image/{image_id}",
        "backdrop_url": "",
        "progress_pct": 0.0,
        "duration_s": 0.0,
        "is_private": True,
        "created_at": created_at,
        "play": {
            "action": "cast",
            "surface_kind": "media.image",
            "surface_url": f"/api/image/{image_id}",
        },
    }


