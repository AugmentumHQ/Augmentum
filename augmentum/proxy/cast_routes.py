_ANDROID_TV_APK_DIR = (
    Path(__file__).parent.parent
    / "cast"
    / "android-tv-receiver"
    / "app"
    / "build"
    / "outputs"
    / "apk"
    / "debug"
)
_ANDROID_TV_APK_PATH = _ANDROID_TV_APK_DIR / "app-debug.apk"
_ANDROID_TV_METADATA_PATH = _ANDROID_TV_APK_DIR / "output-metadata.json"

# (mtime_ns, versionCode, versionName) cache, refreshed when metadata mtime changes.
_apk_version_cache: tuple[int, int, str] | None = None


def _read_android_tv_apk_version() -> tuple[int, str]:
    """Read versionCode + versionName from AGP's output-metadata.json.

    AGP writes this sidecar next to every built APK; it's the canonical
    record of what versionCode is baked into the binary AndroidManifest.
    We mtime-cache so the version endpoint stays cheap under churn.

    Returns (0, "0.0.0") when no APK has been built yet — the client
    falls back to its bundled BuildConfig.VERSION_CODE in that case.
    """
    global _apk_version_cache

    try:
        st = _ANDROID_TV_METADATA_PATH.stat()
    except FileNotFoundError:
        return (0, "0.0.0")

    if _apk_version_cache and _apk_version_cache[0] == st.st_mtime_ns:
        return (_apk_version_cache[1], _apk_version_cache[2])

    import json

    try:
        meta = json.loads(_ANDROID_TV_METADATA_PATH.read_text("utf-8"))
        elem = (meta.get("elements") or [{}])[0]
        version_code = int(elem.get("versionCode") or 0)
        version_name = str(elem.get("versionName") or "0.0.0")
    except (OSError, ValueError, KeyError, json.JSONDecodeError):
        return (0, "0.0.0")

    _apk_version_cache = (st.st_mtime_ns, version_code, version_name)
    return (version_code, version_name)


@pair_router.get("/android-tv/version")
async def android_tv_version(request: Request) -> dict[str, Any]:
    """Return the current Android TV APK version and update settings."""
    apk_exists = _ANDROID_TV_APK_PATH.exists()
    version_code, version_name = _read_android_tv_apk_version() if apk_exists else (0, "0.0.0")

    settings_store = getattr(request.app.state, "settings_store", None)
    if settings_store:
        try:
            tv_update_channel = await settings_store.get("tv_update_channel") or "stable"
            tv_auto_update_raw = await settings_store.get("tv_auto_update")
            tv_auto_update = str(tv_auto_update_raw).lower() in ("true", "1", "yes") if tv_auto_update_raw is not None else True
        except Exception:
            tv_update_channel = "stable"
            tv_auto_update = True
    else:
        tv_update_channel = "stable"
        tv_auto_update = True

    return {
        "versionCode": version_code,
        "versionName": version_name,
        "updateChannel": tv_update_channel,
        "autoUpdate": tv_auto_update,
        "hasUpdate": apk_exists and version_code > 0,
    }

