async def _resolved_gallery_show_private(request: Request) -> bool:
    """Read the privacy-gate setting. Off by default for shared-TV safety."""
    settings_store = getattr(request.app.state, "settings_store", None)
    if settings_store is None:
        return False
    try:
        raw = await settings_store.get("cast_gallery_show_private")
    except Exception:
        return False
    if raw is None or raw == "":
        return False
    # bool settings round-trip as "0"/"1" strings via SettingsStore.
    return str(raw).lower() in ("1", "true", "yes")


async def _fetch_gallery_tiles(
    request: Request,
    idx,
    db,
    user_id: str,
    *,
    category: str,
    limit: int,
    offset: int = 0,
) -> tuple[list[dict[str, Any]], bool]:
    """Return (tiles, gated) for the requested gallery category.

    ``gated`` is True iff the user asked for ``private`` but the
    setting is off — the frontend uses this to show the gating hint
    instead of just an empty grid.
    """
    if category == "private":
        if not await _resolved_gallery_show_private(request):
            return [], True
        cursor = await db.execute(
            "SELECT image_id, prompt, model, width, height, created_at "
            "FROM image_generations "
            "WHERE user_id = ? AND COALESCE(is_private, 0) = 1 "
            "ORDER BY created_at DESC LIMIT ? OFFSET ?",
            (user_id, limit, offset),
        )
        rows = await cursor.fetchall()
        return [_private_image_to_tile(row, user_id) for row in rows], False

    # General + Backgrounds both read from file_index. We need the
    # is_background flag (per-image, lives on image_generations) to
    # partition them, so pull the flag map once.
    flag_map = await _image_gen_flag_map(db, user_id)
    # Fetch wider than the page size — we may discard quite a few
    # entries after applying the flag filter. 5× covers most cases.
    raw_limit = max(limit * 5, 100)
    entries = await idx.list_recent(
        user_id=user_id, kind="image", limit=raw_limit, offset=0,
    )
    want_background = category == "backgrounds"
    out: list[dict[str, Any]] = []
    skipped = 0
    for entry in entries:
        if entry.source == "images":
            _, is_bg = flag_map.get(entry.source_id, (False, False))
        else:
            # Non-image-gen sources (artifacts, chat_images, uploads)
            # have no background concept — they're general by default.
            is_bg = False
        if want_background and not is_bg:
            continue
        if (not want_background) and is_bg:
            continue
        if skipped < offset:
            skipped += 1
            continue
        tile = _entry_to_tile(entry)
        if tile:
            out.append(tile)
            if len(out) >= limit:
                break
    return out, False


# ── Games rail dispatch ──────────────────────────────────────────
# Games don't live in file_index — they're TitleService manifests
# (artifact rows with kind=emulator_rom or streamed_game). The rail
# surfaces the user's playable library; tapping a tile opens the
# game-cast endpoint which spawns an AGSP container + casts the
# stream URL to the selected receiver. Private-images uses the same
# "synthesise a tile from a non-file_index source" pattern.


def _game_subtitle(manifest: Any) -> str:
    """Short context string under the title: system label + last-played hint.

    System label comes from rom_systems for emulator ROMs (so a Wind
    Waker tile reads "GameCube" instead of the bare ``system_id``).
    Native streamed games (Luanti) use the manifest's source label.
    """
    bits: list[str] = []
    raw = manifest.raw_metadata if isinstance(manifest.raw_metadata, dict) else {}
    system_id = str(raw.get("system_id") or "").strip()
    if system_id:
        try:
            from augmentum.titles.rom_systems import get_system
            spec = get_system(system_id)
            bits.append(spec.label if spec is not None else system_id.upper())
        except Exception:
            bits.append(system_id.upper())
    elif manifest.source_id:
        bits.append(str(manifest.source_id))
    last = (manifest.last_played_at or "").strip()
    if last:
        # ISO timestamps look noisy in a one-line subtitle; the date
        # portion alone (YYYY-MM-DD) is the high-signal part for "when
        # did I last play this".
        bits.append(f"last played {last[:10]}")
    return " · ".join(bits)


def _game_to_tile(manifest: Any) -> dict[str, Any] | None:
    """Synthesise a cast-library tile from a TitleManifest.

    Returns ``None`` for titles we can't actually cast (a future-proof
    guard — today all emulator/streamed manifests are eligible). Tile
    shape matches ``_entry_to_tile`` so the controller's renderer needs
    zero special-casing besides the new ``cast_game`` play.action.

    Cover art is left blank — the rom_systems catalog doesn't carry
    per-title art and the controller's tile renderer already handles
    missing cover_url with a procedural placeholder. Adding real cover
    sourcing (TheGamesDB / user-uploaded) is a follow-up.
    """
    raw = manifest.raw_metadata if isinstance(manifest.raw_metadata, dict) else {}
    system_id = str(raw.get("system_id") or "").strip()
    return {
        "file_id": manifest.id,
        "title": manifest.title or "Untitled game",
        "subtitle": _game_subtitle(manifest),
        "kind": "game",
        "entity_kind": manifest.kind,
        "source": manifest.source_id or "",
        "cover_url": "",
        "backdrop_url": "",
        "progress_pct": 0.0,
        "duration_s": float(manifest.total_play_time_s or 0),
        "system_id": system_id,
        "play": {
            # ``cast_game`` tells the controller to POST to the
            # /api/cast/games/{file_id}/start endpoint rather than the
            # generic /api/cast/send. The endpoint owns the runtime
            # spawn + surface dispatch atomically.
            "action": "cast_game",
            "surface_kind": SURFACE_STREAM,
            "surface_url": f"/api/cast/games/{manifest.id}/start",
        },
    }


async def _fetch_game_tiles(
    request: Request, user_id: str, *, limit: int, offset: int = 0,
) -> list[dict[str, Any]]:
    """Return the user's playable-game tiles for the games rail.

    Sources from ``TitleService.list_titles`` across the two playable
    kinds (emulator ROMs + native streamed games). For emulator ROMs
    we filter to systems that have a streaming runtime available —
    cast surfaces ONLY make sense for streaming-capable titles since
    the browser-runnable WASM path is single-device (the phone).
    Browser-runnable ROMs surface elsewhere; surfacing them here too
    would just confuse "tap to play on TV" with "tap to play here".
    """
    title_service = getattr(request.app.state, "title_service", None)
    if title_service is None:
        return []
    from augmentum.titles import (
        KIND_EMULATOR_ROM,
        KIND_STREAMED_GAME,
    )
    from augmentum.titles.rom_systems import get_system

    out: list[dict[str, Any]] = []
    # list_titles has no multi-kind filter; do two queries and merge.
    # Volume is modest (hundreds of titles per user at most) so this
    # is cheap. Streamed games come first because they're always
    # cast-capable; ROMs follow filtered by streaming_profile presence.
    try:
        streamed = await title_service.list_titles(
            user_id=user_id, kind=KIND_STREAMED_GAME, limit=limit + offset,
        )
    except Exception as exc:
        log.warning("cast_games_streamed_fetch_failed", error=str(exc))
        streamed = []
    try:
        roms = await title_service.list_titles(
            user_id=user_id, kind=KIND_EMULATOR_ROM, limit=200,
        )
    except Exception as exc:
        log.warning("cast_games_roms_fetch_failed", error=str(exc))
        roms = []

    eligible: list[Any] = list(streamed)
    for m in roms:
        sid = str((m.raw_metadata or {}).get("system_id", "")).strip()
        spec = get_system(sid) if sid else None
        if spec is not None and spec.streaming_profile:
            eligible.append(m)

    # Most-recently-played first (DESC by last_played_at) for
    # titles the user has touched; never-played follow alphabetically.
    # Mirrors the Continue rail behavior.
    timestamped = [m for m in eligible if (m.last_played_at or "").strip()]
    timestamped.sort(key=lambda m: m.last_played_at or "", reverse=True)
    rest = [m for m in eligible if not (m.last_played_at or "").strip()]
    rest.sort(key=lambda m: m.title.casefold())
    ordered = timestamped + rest

    page = ordered[offset:offset + limit]
    for manifest in page:
        tile = _game_to_tile(manifest)
        if tile is not None:
            out.append(tile)
    return out


def _comic_series_key(meta: dict[str, Any]) -> tuple[str, str]:
    """Series-grouping key for a comic chapter entry.

    Komga: chapter extras carry ``komga_series_id`` (set by
      ``KomgaProvider._fetch_series_books``).
    Suwayomi: chapter extras carry ``suwayomi_manga_id`` (set by
      ``_chapter_to_catalog_item`` via the manga_payload). Fall back to
      parsing the first segment of ``external_id`` (``{manga_id}.…``)
      for legacy 2-part entries where the manga_payload didn't land.
    Fall through: empty tuple = "don't group" — the chapter surfaces
      as its own tile (e.g. one-shots, unknown providers).
    """
    provider = str(meta.get("provider") or "").strip().lower()
    extra = meta.get("extra") if isinstance(meta.get("extra"), dict) else {}
    if provider == "komga":
        sid = str(extra.get("komga_series_id") or "").strip()
        return ("komga", sid) if sid else ("", "")
    if provider == "suwayomi":
        mid = str(extra.get("suwayomi_manga_id") or "").strip()
        if not mid:
            ext = str(meta.get("external_id") or "")
            mid = ext.split(".", 1)[0] if ext else ""
        return ("suwayomi", mid) if mid else ("", "")
    return ("", "")


def _comic_series_tile(rep_entry, chapter_count: int) -> dict[str, Any] | None:
    """Build a series pseudo-tile from a representative chapter.

    The tile carries the rep chapter's file_id as ``file_id`` — the
    drill-in endpoint uses it to re-resolve the series and list its
    chapters. ``action='browse_series'`` keeps the controller from
    casting it directly. Cover is the rep chapter's cover (provider
    cover endpoints serve a series-level image for any chapter
    request, so this works without provider-specific cover URLs).

    The tile also carries fields used for server-side sort/filter on
    the See-all view: ``chapter_count`` (numeric), ``series_status``
    (provider's status string, lowercased), and ``last_added_ts``
    (the representative chapter's created_at — since the chapter list
    is pre-sorted newest-first, the representative IS the most-recent
    chapter and its timestamp is the series's "recently active" key).
    """
    meta = rep_entry.source_metadata if isinstance(rep_entry.source_metadata, dict) else {}
    extra = meta.get("extra") if isinstance(meta.get("extra"), dict) else {}
    series_name = str(extra.get("series_name") or rep_entry.name or "Series").strip()
    parts = [f"{chapter_count} chapter" + ("" if chapter_count == 1 else "s")]
    author = str(meta.get("author") or "").strip()
    if author:
        parts.append(author)
    status = str(extra.get("status") or "").strip().lower() or "unknown"
    return {
        "file_id": rep_entry.id,
        "title": series_name,
        "subtitle": " · ".join(parts),
        "kind": "comic",
        "entity_kind": "comic_series",
        "source": rep_entry.source or "",
        "cover_url": f"/api/media/cover/{rep_entry.id}",
        "backdrop_url": "",
        "progress_pct": 0.0,
        "duration_s": 0.0,
        "chapter_count": chapter_count,
        "series_status": status,
        "last_added_ts": rep_entry.created_at or "",
        # comic_series linkage — lets drill-in headers fetch the rich
        # series record (/api/files/comics/series/{id}: publisher,
        # years, genres, description) without a second chapter scan.
        "series_id": getattr(rep_entry, "series_id", None) or "",
        "play": {
            "action": "browse_series",
            "surface_kind": "",
            "surface_url": "",
        },
    }


async def _collapse_resume_by_series(
    entries: Iterable[Any],
    limit: int,
    *,
    idx: Any,
    user_id: str,
) -> list[dict[str, Any]]:
    """Dedupe the Continue rail so a user with 8 mid-watch episodes of
    one show sees ONE card, not eight.

    For VIDEO episodes specifically, the resulting tile uses the SERIES
    poster + series name (so it matches the Shows rail visually) but
    keeps the EPISODE as the play target + progress source. Tapping it
    casts the in-progress episode directly — no detour through the
    season picker. Same pattern Jellyfin / Plex use for Continue.

    Strategy:
      * Episodes (kind=video, entity_kind=episode): look up the series
        row by (server_id, grandparent_external_id). When found, build
        a hybrid tile (series visuals + episode play). When the series
        row isn't indexed yet, fall back to the episode's own tile.
      * Audiobook chapters / podcasts collapse by ``parent_external_id``
        with the episode's own tile (the upstream usually carries the
        right cover at the chapter level for audio).
      * Comic chapters collapse via the same ``_comic_series_key``
        helper the catalog comic rail uses.
      * Movies / one-shot audio / standalone images / series with no
        episodes-yet pass through as their own cards.
    """
    # Prefetch all series rows for this user once so each episode rep
    # lookup is O(1) over the rep set. 774 series in the typical
    # library is well under the 5000 cap.
    series_by_ext: dict[tuple[str, str], Any] = {}
    try:
        all_series = await idx.list_recent(
            user_id=user_id, kind="video",
            entity_kinds=["series"], limit=5000,
        )
        for s in all_series:
            sm = s.source_metadata if isinstance(s.source_metadata, dict) else {}
            sid = str(sm.get("server_id") or "").strip()
            eid = str(sm.get("external_id") or "").strip()
            if sid and eid:
                series_by_ext[(sid, eid)] = s
    except Exception as exc:
        log.warning("cast_resume_series_prefetch_failed", error=str(exc))

    seen: set[tuple[str, str]] = set()
    out: list[dict[str, Any]] = []
    for entry in entries:
        meta = entry.source_metadata if isinstance(entry.source_metadata, dict) else {}
        kind = (entry.kind or "").lower()
        entity_kind = str(meta.get("entity_kind") or "").strip().lower()
        server_id = str(meta.get("server_id") or "").strip()
        # Build a (group_kind, group_id) key so a comic series and a
        # video series that share an external_id by coincidence can't
        # collide.
        key: tuple[str, str] | None = None
        if kind == "video" and entity_kind == "episode":
            gp = str(meta.get("grandparent_external_id") or "").strip()
            if gp and server_id:
                key = ("video_series", f"{server_id}:{gp}")
        elif kind == "audio":
            parent = str(meta.get("parent_external_id") or "").strip()
            if parent and server_id:
                key = ("audio_parent", f"{server_id}:{parent}")
        elif kind == "comic":
            ck = _comic_series_key(meta)
            if ck[1]:
                key = ("comic_series", f"{ck[0]}:{ck[1]}")
        if key is not None:
            if key in seen:
                continue
            seen.add(key)

        # For video episodes, swap the visuals for the series's poster
        # + name when we have the series indexed. Play target stays on
        # the episode so the tap resumes where the user left off.
        tile: dict[str, Any] | None = None
        if kind == "video" and entity_kind == "episode":
            gp = str(meta.get("grandparent_external_id") or "").strip()
            if gp and server_id:
                series = series_by_ext.get((server_id, gp))
                if series is not None:
                    tile = _episode_resume_as_series_tile(entry, series)
        if tile is None:
            tile = _entry_to_tile(entry)
        if not tile:
            continue
        out.append(tile)
        if len(out) >= limit:
            break
    return out


def _episode_resume_as_series_tile(
    episode: Any, series: Any,
) -> dict[str, Any] | None:
    """Hybrid tile: series visuals (poster, name) + episode play target.

    Used by the Continue rail so a user mid-watching "Show — S2E5"
    sees a tile that looks like the Show poster but resumes the
    specific episode on tap. Progress bar reflects the episode's
    current position; subtitle line shows "S2E5 · episode title".
    """
    emeta = episode.source_metadata if isinstance(episode.source_metadata, dict) else {}
    smeta = series.source_metadata if isinstance(series.source_metadata, dict) else {}
    if not emeta or not smeta:
        return None
    season_n = int(emeta.get("season_number") or 0)
    ep_n = int(emeta.get("episode_number") or 0)
    ep_name = (episode.name or "").strip()
    sub_bits: list[str] = []
    if season_n and ep_n:
        sub_bits.append(f"S{season_n}E{ep_n:02d}")
    if ep_name:
        sub_bits.append(ep_name)
    subtitle = " · ".join(sub_bits)

    # Cover URL — same per-source routing as _entry_to_tile, but
    # pointing at the SERIES row, not the episode.
    s_server_id = str(smeta.get("server_id") or "").strip()
    if s_server_id:
        cover_url = f"/api/media/cover/{series.id}"
    else:
        cover_url = f"/api/files/thumb/{series.id}?size=300"

    return {
        "file_id": episode.id,           # progress poll keys on this
        "title": series.name or "Series",
        "subtitle": subtitle,
        "kind": "video",
        # Forced "series" so the renderer uses a 2:3 portrait poster,
        # matching the Shows rail visually instead of an episode-style
        # landscape thumb.
        "entity_kind": "series",
        "source": episode.source or "",
        "cover_url": cover_url,
        "backdrop_url": f"/api/media/backdrop/{series.id}",
        "progress_pct": float(emeta.get("progress_pct") or 0.0),
        "duration_s": float(emeta.get("duration_s") or 0.0),
        "play": {
            "action": "cast",            # NOT browse_series — direct cast
            "surface_kind": "html.generic",
            "surface_url": f"/ui/cast-video/?id={episode.id}",
        },
    }


def _collapse_comics_to_series(
    entries: Iterable[Any],
    limit: int,
) -> list[dict[str, Any]]:
    """Group raw comic chapters into one tile per series.

    Walks chapters in their incoming order (typically recently-added /
    updated) and keeps the first chapter seen for each series as the
    representative. Counts every chapter in the group so the tile can
    show "12 chapters". Ungrouped chapters (one-shots, providers we
    don't know how to group) fall through as their own tiles.

    Capped at ``limit`` tiles so the rail stays compact."""
    series_rep: "OrderedDict[tuple[str, str], Any]" = OrderedDict()
    series_count: dict[tuple[str, str], int] = {}
    one_shots: list[Any] = []
    for entry in entries:
        meta = entry.source_metadata if isinstance(entry.source_metadata, dict) else {}
        key = _comic_series_key(meta)
        if not key[1]:
            one_shots.append(entry)
            continue
        if key not in series_rep:
            series_rep[key] = entry
        series_count[key] = series_count.get(key, 0) + 1

    out: list[dict[str, Any]] = []
    for key, rep in series_rep.items():
        tile = _comic_series_tile(rep, series_count.get(key, 1))
        if tile:
            out.append(tile)
        if len(out) >= limit:
            return out
    for entry in one_shots:
        if len(out) >= limit:
            break
        tile = _entry_to_tile(entry)
        if tile:
            out.append(tile)
    return out


@router.get("/library/section/{slug}")
async def cast_library_section(
    slug: str,
    request: Request,
    offset: int = 0,
    limit: int = 60,
    q: str = "",
    status: str = "",
    kind: str = "",
) -> dict[str, Any]:
    """Paginated view of one rail — backs the controller's "See all"
    drill-in. Same tile shape as /library/home so the client renders
    a section the same way regardless of source.

    Sort orders accepted via ?sort= : "newest", "name", "year_desc",
    "year_asc", "author", "progress" (the last two only meaningful on
    media-server-backed sections). When omitted, the section's
    home_query sort applies.

    Optional ``?q=`` runs an FTS5 title search scoped to this section's
    kind/entity filters. Empty string (default) preserves the
    list_recent browsing path. Gallery + resume ignore ``q`` — the
    controller hides the search input there.

    ``?status=`` maps to media_status (``in_progress`` / ``finished``
    / ``not_started``) for video + audio sections. Ignored for comics
    (which use ``?filter=`` for series status) and gallery.

    ``?kind=`` overrides the section's default kind filter — currently
    only used by the recently_added drill-in to surface a single media
    kind (Movies / Shows / Audiobooks / Comics chip).
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    spec = _CAST_LIBRARY_SECTIONS.get(slug)
    if spec is None:
        raise HTTPException(404, f"unknown section {slug!r}")
    idx = getattr(request.app.state, "file_index", None)
    if idx is None:
        raise HTTPException(503, "file index not initialised")

    q_str = (q or "").strip()
    section_query = dict(spec["query"])
    section_query["limit"] = max(1, min(int(limit), 200))
    section_query["offset"] = max(0, int(offset))
    sort_override = request.query_params.get("sort")
    if sort_override:
        section_query["sort"] = sort_override

    # ``?status=`` — UI chip for "All / Unwatched / In progress / Finished"
    # on movies/shows/audiobooks. "all" (default) means no filter. Other
    # values feed file_index.list_recent/search as media_status; rows
    # without progress metadata simply don't match, which is the right
    # behavior (a Komga comic doesn't have a watched flag).
    status_norm = (status or "").strip().lower()
    if status_norm and status_norm != "all" and slug not in ("comics", "gallery"):
        section_query["media_status"] = status_norm

    # ``?kind=`` — recently_added's "All / Movies / Shows / Audiobooks /
    # Comics" chip. Overrides the spec's positive kind filter, but
    # preserves the spec's exclude_kinds/exclude_entity_kinds so docs
    # still stay out of the recently-added rail.
    kind_norm = (kind or "").strip().lower()
    if kind_norm and slug == "recently_added":
        # The chip carries a "kind" value plus, for movies/shows, an
        # implied entity_kind narrowing. We translate the user-facing
        # token into the right file_index filters.
        _KIND_CHIP_TRANSLATIONS = {
            "video":      {"kind": "video"},
            "movie":      {"kind": "video", "entity_kinds": ["movie"]},
            "series":     {"kind": "video", "entity_kinds": ["series"]},
            "audio":      {"kind": "audio"},
            "comic":      {"kind": "comic"},
        }
        translation = _KIND_CHIP_TRANSLATIONS.get(kind_norm)
        if translation:
            section_query.update(translation)

    # ``q`` only applies to text-searchable sections. Gallery is
    # bypassed because image rows rarely carry meaningful title text;
    # resume is filtered out client-side (no see-all from that rail)
    # but we belt-and-brace it here in case a caller crafts the URL.
    if q_str and slug in ("gallery", "resume"):
        q_str = ""

    # Comics section is series-collapsed — pagination has to operate on
    # the SERIES list (post-collapse), not the chapter list (pre-collapse).
    # If we paged the chapter list, shifting by `limit` rows out of 20k
    # chapters barely changes which series surface (page 2 = page 1).
    # So: pull the full chapter pool with offset=0, collapse to all
    # series tiles, optionally filter + sort, then slice by the
    # client's offset/limit.
    is_comic_slug = section_query.get("kind") == "comic"
    if is_comic_slug:
        # ``section_query`` may carry extra filters (sort, source, etc.)
        # that should ride along. The auto-sized fetch overrides
        # limit/offset.
        extra = {k: v for k, v in section_query.items()
                 if k not in ("user_id", "kind", "limit", "offset")}
        try:
            if q_str:
                # Title search: route through FTS over the user's whole
                # comic library. Cannot use the collapsed-series cache
                # because the search-filtered result varies per query —
                # cache invalidation would defeat the cache.
                ceiling = await _resolved_comic_ceiling(request)
                entries = await idx.search(
                    q_str, user_id=user.id, kind="comic", limit=ceiling,
                )
                all_series = _collapse_comics_to_series(entries, len(entries) + 1)
            else:
                # Cached collapse — kills the 6 s / 20k-row fetch on
                # every poll. Cache key includes chapter count so any
                # sync activity invalidates immediately.
                all_series = await _get_collapsed_comic_series(
                    request, idx, user.id,
                )
        except Exception as exc:
            log.warning("cast_library_section_paged_failed", slug=slug, error=str(exc))
            all_series = []
        # Filter — see-all takes a single ``filter`` param scoped to
        # comics. "all" (default) keeps everything; status filters
        # match the canonical extra.status values written by Komga +
        # Suwayomi at sync time.
        filter_val = (request.query_params.get("filter") or "all").strip().lower()
        if filter_val in {"ongoing", "completed", "cancelled", "unknown"}:
            all_series = [t for t in all_series if t.get("series_status") == filter_val]
        # Sort — defaults to alphabetical for see-all since random
        # makes paginated browsing useless (would re-shuffle on every
        # "Load more"). The home rail's random behavior is separate.
        sort_val = (request.query_params.get("sort") or "name_asc").strip().lower()
        if sort_val == "name_desc":
            all_series.sort(key=lambda t: t["title"].casefold(), reverse=True)
        elif sort_val == "active":
            all_series.sort(key=lambda t: t.get("last_added_ts") or "", reverse=True)
        elif sort_val == "chapters":
            all_series.sort(key=lambda t: t.get("chapter_count") or 0, reverse=True)
        else:  # name_asc + fallback
            all_series.sort(key=lambda t: t["title"].casefold())
        page_offset = section_query["offset"]
        page_limit = section_query["limit"]
        items = all_series[page_offset:page_offset + page_limit]
        has_more = page_offset + len(items) < len(all_series)
    elif slug == "gallery":
        # Three-folder gallery: general / backgrounds / private.
        # Default category is "general" (matches the home rail).
        category = (request.query_params.get("category") or "general").strip().lower()
        if category not in VALID_GALLERY_CATEGORIES:
            category = "general"
        db_conn = _app_db_conn(request)
        gated = False
        items: list[dict[str, Any]] = []
        if db_conn is not None:
            try:
                items, gated = await _fetch_gallery_tiles(
                    request, idx, db_conn, user.id,
                    category=category,
                    limit=section_query["limit"], offset=section_query["offset"],
                )
            except Exception as exc:
                log.warning(
                    "cast_gallery_section_failed",
                    slug=slug, category=category, error=str(exc),
                )
        has_more = (not gated) and len(items) >= section_query["limit"]
        return {
            "id": slug,
            "title": spec["title"],
            "items": items,
            "offset": section_query["offset"],
            "limit": section_query["limit"],
            "has_more": has_more,
            "category": category,
            "private_gated": gated,
        }
    elif slug == "games":
        try:
            items = await _fetch_game_tiles(
                request, user.id,
                limit=section_query["limit"], offset=section_query["offset"],
            )
        except Exception as exc:
            log.warning(
                "cast_games_section_failed",
                slug=slug, error=str(exc),
            )
            items = []
        has_more = len(items) >= section_query["limit"]
    else:
        try:
            if q_str:
                # FTS search keeps the section's kind/entity filters so
                # results stay scoped to the user's view (e.g. "shows"
                # search returns series rows, not loose episodes).
                # ``exclude_kinds`` from the spec (recently_added drops
                # docs) is post-applied below since search() doesn't
                # accept that kw. Slight over-fetch covers post-filter
                # drop without re-paginating.
                search_kwargs: dict[str, Any] = {
                    "user_id": user.id,
                    "limit": section_query["limit"] * 2,
                    "offset": section_query["offset"],
                }
                for key in (
                    "kind", "entity_kind", "entity_kinds",
                    "exclude_entity_kinds", "source", "sources",
                    "media_status",
                ):
                    if key in section_query:
                        search_kwargs[key] = section_query[key]
                entries = await idx.search(q_str, **search_kwargs)
                exclude_kinds = set(section_query.get("exclude_kinds") or [])
                if exclude_kinds:
                    entries = [e for e in entries if e.kind not in exclude_kinds]
                entries = entries[: section_query["limit"]]
            else:
                entries = await idx.list_recent(user_id=user.id, **section_query)
        except Exception as exc:
            log.warning("cast_library_section_paged_failed", slug=slug, error=str(exc))
            entries = []
        items = [t for t in (_entry_to_tile(e) for e in entries) if t]
        # ``has_more`` is set when we got a full page back — true
        # negative rate is low; another fetch is the way to find out.
        has_more = len(items) >= section_query["limit"]

    return {
        "id": slug,
        "title": spec["title"],
        "items": items,
        "offset": section_query["offset"],
        "limit": section_query["limit"],
        "has_more": has_more,
    }


# Search-result grouping. Display order is deliberate: the kinds the
# user most likely typed a title for come first. Slugs reuse the rail
# vocabulary so clients can apply the same hidden-rail prefs they use
# for /library/home (e.g. Media hides "gallery" in search too).
_SEARCH_BUCKETS: tuple[tuple[str, str], ...] = (
    ("movies", "Movies"),
    ("shows", "Shows"),
    ("episodes", "Episodes"),
    ("audiobooks", "Audio"),
    ("comics", "Comics"),
    ("videos", "Videos"),
    ("gallery", "Images"),
)


@router.get("/library/search")
async def cast_library_search(
    request: Request, q: str = "", limit: int = 80,
) -> dict[str, Any]:
    """Cross-library tile search. One FTS pass over the user's whole
    file_index, grouped into kind buckets that render with the same
    rail/tile components as /library/home.

    Powers the Media surface's search chrome first; cast-control can
    adopt the same endpoint when its search lands. Seasons are excluded
    (never a useful search hit — the series card covers them) and doc
    rows are dropped (documents have their own search surfaces).
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    idx = getattr(request.app.state, "file_index", None)
    q_str = (q or "").strip()
    if idx is None or not q_str:
        return {"sections": [], "query": q_str}
    limit = max(1, min(int(limit), 200))

    try:
        entries = await idx.search(
            q_str,
            user_id=user.id,
            exclude_entity_kinds=["season"],
            limit=limit,
        )
    except Exception as exc:
        log.warning("cast_library_search_failed", error=str(exc))
        entries = []

    grouped: dict[str, list[dict[str, Any]]] = {
        slug: [] for slug, _ in _SEARCH_BUCKETS
    }
    for entry in entries:
        if (entry.kind or "").lower() == "doc":
            continue
        tile = _entry_to_tile(entry)
        if not tile:
            continue
        kind = tile["kind"]
        if kind == "video":
            slug = {
                "movie": "movies",
                "series": "shows",
                "episode": "episodes",
            }.get(tile["entity_kind"], "videos")
        elif kind == "audio":
            slug = "audiobooks"
        elif kind == "comic":
            slug = "comics"
        elif kind == "image":
            slug = "gallery"
        else:
            continue
        grouped[slug].append(tile)

    sections = [
        {"id": slug, "title": title, "items": grouped[slug]}
        for slug, title in _SEARCH_BUCKETS
        if grouped[slug]
    ]
    return {"sections": sections, "query": q_str}


@router.get("/library/chapters/{file_id}")
async def cast_library_chapters(
    file_id: str, request: Request,
) -> dict[str, Any]:
    """List the chapters of a comic series, ordered for drill-in.

    Accepts any chapter's ``file_id`` (typically the representative
    one carried on a series-collapsed tile). Looks up its series key
    via ``_comic_series_key`` then scans the user's comic library for
    every chapter sharing that key. Returns chapters in reading order
    (low chapter number first), plus a thin ``series`` block so the
    drill-in header can show series name / cover.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    idx = getattr(request.app.state, "file_index", None)
    if idx is None:
        raise HTTPException(503, "file index not initialised")

    rep_entry = await idx.get(file_id, user_id=user.id)
    if rep_entry is None or rep_entry.kind != "comic":
        raise HTTPException(404, "comic chapter not found")

    rep_meta = rep_entry.source_metadata if isinstance(
        rep_entry.source_metadata, dict
    ) else {}
    target_key = _comic_series_key(rep_meta)
    if not target_key[1]:
        # Ungrouped chapter (one-shot / unknown provider): return just it.
        tile = _entry_to_tile(rep_entry)
        return {
            "series": tile,
            "chapters": [tile] if tile else [],
        }

    try:
        # Auto-sized fetch — see _fetch_user_comic_chapters. The
        # drill-in MUST see every chapter the rail tile represents or
        # we hand the user an empty list ("No chapters indexed yet"),
        # so this path is intentionally generous with its fetch size.
        all_comics = await _fetch_user_comic_chapters(request, idx, user.id)
    except Exception as exc:
        log.warning(
            "cast_library_chapters_query_failed",
            file_id=file_id, error=str(exc),
        )
        all_comics = []

    chapters: list[tuple[float, str, dict[str, Any]]] = []
    for entry in all_comics:
        emeta = entry.source_metadata if isinstance(entry.source_metadata, dict) else {}
        if _comic_series_key(emeta) != target_key:
            continue
        tile = _entry_to_tile(entry)
        if not tile:
            continue
        eextra = emeta.get("extra") if isinstance(emeta.get("extra"), dict) else {}
        # Chapter sort: source-provider order FIRST — that's how
        # Suwayomi/Komga address chapters internally, it's what
        # /api/files/comics/series/{id}/chapters uses, and it's the
        # order the comic reader's prev/next siblings follow. Sorting
        # here by chapter_number alone made the drill-in list disagree
        # with the reader's transition order for series with decimal /
        # missing numbering. chapter_number + name stay as tie-breaks
        # (float() handles "12.5" half-chapters).
        try:
            source_order = int(eextra.get("chapter_source_order") or 0)
        except (TypeError, ValueError):
            source_order = 0
        try:
            chap_num = float(eextra.get("chapter_number") or 0)
        except (TypeError, ValueError):
            chap_num = 0.0
        chapters.append((source_order, chap_num, entry.name or "", {
            **tile,
            "chapter_number": chap_num,
            "volume_number": eextra.get("volume_number") or "",
        }))
    chapters.sort(key=lambda row: (row[0], row[1], row[2]))

    series_tile = _comic_series_tile(rep_entry, len(chapters))
    return {
        "series": series_tile,
        "chapters": [row[3] for row in chapters],
    }


@router.get("/library/episodes/{series_file_id}")
async def cast_library_episodes(
    series_file_id: str, request: Request,
) -> dict[str, Any]:
    """List the episodes of a series, season-grouped + ordered for
    drill-in from a series card tap.

    Resolves children by matching ``source_metadata.grandparent_external_id``
    on each episode against the series's ``external_id`` — same way
    /api/media/details traverses the Emby/Jellyfin hierarchy.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    idx = getattr(request.app.state, "file_index", None)
    if idx is None:
        raise HTTPException(503, "file index not initialised")

    series_entry = await idx.get(series_file_id, user_id=user.id)
    if series_entry is None:
        raise HTTPException(404, "series not found")
    series_meta = series_entry.source_metadata if isinstance(
        series_entry.source_metadata, dict
    ) else {}
    series_external_id = str(series_meta.get("external_id") or "").strip()
    series_server_id = str(series_meta.get("server_id") or "").strip()

    if not series_external_id or not series_server_id:
        return {
            "series": _entry_to_tile(series_entry),
            "seasons": [],
        }

    # Query episodes belonging to THIS series at the SQL level via JSON
    # predicates. The previous approach (over-fetch ``list_recent`` and
    # filter in Python) only saw the 1000 most-recently-touched videos
    # across the user's entire catalog — for a library with thousands
    # of episodes, that meant series drill-in returned only the handful
    # whose updated_at landed in that window. A user with "5 unwatched"
    # on a series card would see 1 episode if the others hadn't been
    # touched recently.
    #
    # The SQL filters on grandparent_external_id (series id) + server_id
    # so the query is bounded by the actual size of the series, not the
    # global catalog. Sort is intrinsic so we don't need a Python pass
    # to order by season/episode.
    from augmentum.vfs.index import _ENTRY_COLUMNS
    sql = (
        f"SELECT {_ENTRY_COLUMNS} FROM file_index "
        "WHERE user_id = ? "
        "  AND kind = 'video' "
        "  AND is_trashed = 0 "
        "  AND json_extract(source_metadata, '$.entity_kind') = 'episode' "
        "  AND json_extract(source_metadata, '$.grandparent_external_id') = ? "
        "  AND json_extract(source_metadata, '$.server_id') = ? "
        "ORDER BY "
        "  COALESCE(CAST(json_extract(source_metadata, '$.season_number') AS INTEGER), 0), "
        "  COALESCE(CAST(json_extract(source_metadata, '$.episode_number') AS INTEGER), 0)"
    )
    all_videos: list[Any] = []
    try:
        # idx._db / _row_to_entry are private but stable — the canonical
        # way to read file_index rows. If a new parent-link filter is
        # ever added to list_recent, swap to that.
        cursor = await idx._db.execute(  # noqa: SLF001
            sql, (user.id, series_external_id, series_server_id),
        )
        try:
            rows = await cursor.fetchall()
        finally:
            await cursor.close()
        all_videos = [idx._row_to_entry(row) for row in rows]  # noqa: SLF001
    except Exception as exc:
        log.warning("cast_library_episodes_query_failed", series=series_file_id, error=str(exc))
        all_videos = []

    # Group episodes by season number, ordered ascending. SQL already
    # ordered by (season, episode) so we just have to bucket.
    seasons_map: dict[int, list[dict[str, Any]]] = {}
    for e in all_videos:
        emeta = e.source_metadata if isinstance(e.source_metadata, dict) else {}
        tile = _entry_to_tile(e)
        if not tile:
            continue
        season_n = int(emeta.get("season_number") or 0)
        seasons_map.setdefault(season_n, []).append({
            **tile,
            "episode_number": int(emeta.get("episode_number") or 0),
            "season_number": season_n,
        })

    seasons = []
    for season_n in sorted(seasons_map.keys()):
        eps = sorted(
            seasons_map[season_n],
            key=lambda t: t.get("episode_number", 0),
        )
        seasons.append({
            "season_number": season_n,
            "label": f"Season {season_n}" if season_n > 0 else "Specials",
            "episodes": eps,
        })

    return {
        "series": _entry_to_tile(series_entry),
        "seasons": seasons,
    }


