@router.put("/trusted-receivers/{trusted_id}/prefs")
async def put_trusted_receiver_prefs(
    trusted_id: str, request: Request,
) -> dict[str, Any]:
    """Replace this receiver's prefs bag wholesale. Body is the new
    bag; unknown keys are dropped and type-incorrect values fall back
    to the default (see ``coerce_prefs``). Returns the merged-with-
    defaults bag the client should adopt locally.
    """
    user = request.scope.get("user")
    if user is None:
        raise HTTPException(401, "auth required")
    store = getattr(request.app.state, "trusted_receiver_store", None)
    if store is None:
        raise HTTPException(503, "trusted-receiver store not initialised")
    try:
        body = await request.json()
    except Exception:
        raise HTTPException(422, "invalid JSON body")
    if not isinstance(body, dict):
        raise HTTPException(422, "body must be an object")
    incoming = body.get("prefs") if "prefs" in body else body
    from augmentum.cast.receiver_prefs import coerce_prefs, with_defaults
    cleaned = coerce_prefs(incoming if isinstance(incoming, dict) else {})
    if not await store.set_prefs(trusted_id, user_id=user.id, prefs=cleaned):
        raise HTTPException(404, "trusted receiver not found or revoked")
    merged = with_defaults(cleaned)
    # Live-push the new bag to any currently-connected sessions of
    # this trusted receiver. The receiver-side ``prefs_changed`` handler
    # adopts the bag without a page reload. Multiple sessions of the
    # same TV (rare — but a browser tab + the APK could overlap during
    # debugging) all get the cmd; idempotent if a connection drops
    # mid-send.
    registry = getattr(request.app.state, "receiver_registry", None)
    if registry is not None:
        from augmentum.cast.receiver_protocol import CMD_PREFS_CHANGED, ReceiverCmd
        cmd = ReceiverCmd(cmd=CMD_PREFS_CHANGED, args={"prefs": merged})
        for conn in list(registry.list_for_user(user.id)):
            if conn.trusted_id == trusted_id:
                try:
                    await registry.send(conn.registration_id, cmd)
                except Exception as exc:
                    log.warning(
                        "cast_prefs_changed_push_failed",
                        registration_id=conn.registration_id,
                        trusted_id=trusted_id,
                        error=str(exc),
                    )
    return {"prefs": merged}


